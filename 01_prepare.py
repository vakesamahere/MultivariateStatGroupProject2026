# 3. breakdowns
# --------------------------------------------------------------------------
def build_breakdowns(br: pd.DataFrame, ops: pd.DataFrame, t: pd.DataFrame, trains: pd.DataFrame,
                     stations: dict) -> pd.DataFrame:
    """Pair BREAKDOWN -> RECOVERED per train and link each incident to the movement stream."""
    section("3a. breakdown_recovery audit")
    br = br.copy()
    br["timestamp"] = to_ts(br["timestamp"])
    check("unparseable timestamps", int(br["timestamp"].isna().sum()))
    table(br["event_description"].value_counts())
    check("unknown event codes", int((~br["event_description"].isin(BR_EVENTS)).sum()))
    check("trains not in train_information", int((~br["train_id"].isin(trains["train_id"])).sum()))
    check("rows out of timestamp order", int((br["timestamp"].diff() < pd.Timedelta(0)).sum()))
    lbl = br["station"]
    seg = lbl.str.extract(SEG_RE)
    known = set(stations["st"]["station_id"])
    is_seg = seg[0].notna()
    check("location labels unknown / malformed",
          int((~is_seg & ~lbl.isin(known)).sum() + (is_seg & (~seg[0].isin(known) | ~seg[1].isin(known))).sum()))
    log(f"- trains with >=1 incident: {br['train_id'].nunique()} of {len(trains)}")

    # pairing: per train, a BREAKDOWN must be followed by a RECOVERED at the same location
    b = br.sort_values(["train_id", "timestamp"], kind="stable").reset_index(drop=True)
    nxt = b.shift(-1)
    is_pair = (b["event_description"].eq("BREAKDOWN") & nxt["event_description"].eq("RECOVERED")
               & b["train_id"].eq(nxt["train_id"]))
    paired_rows = is_pair | is_pair.shift(1, fill_value=False)
    check("unpaired BREAKDOWN rows", int((b["event_description"].eq("BREAKDOWN") & ~paired_rows).sum()))
    check("unpaired / orphan RECOVERED rows", int((b["event_description"].eq("RECOVERED") & ~paired_rows).sum()))
    check("pairs whose RECOVERED location differs from BREAKDOWN location",
          int((is_pair & b["station"].ne(nxt["station"])).sum()))
    check("pairs spanning two dates", int((is_pair & b["timestamp"].dt.normalize().ne(nxt["timestamp"].dt.normalize())).sum()))
    p = b[is_pair].copy()
    p["recovery_ts"] = nxt.loc[is_pair, "timestamp"]
    p = p.rename(columns={"timestamp": "onset_ts", "station": "location"}).drop(columns="event_description")
    p = p.sort_values("onset_ts").reset_index(drop=True)
    p.insert(0, "incident_id", [f"BD{i + 1:03d}" for i in range(len(p))])
    p["duration_s"] = (p["recovery_ts"] - p["onset_ts"]).dt.total_seconds()
    check("duration_s <= 0", int((p["duration_s"] <= 0).sum()))

    parts = p["location"].str.extract(SEG_RE)
    p["location_type"] = np.where(parts[0].notna(), "segment", "station")
    p["from_station"] = parts[0].fillna(p["location"])
    p["to_station"] = parts[1]                              # NA for station incidents
    p = p.merge(trains[["train_id", "line_id", "route_id", "train_type", "batch_number"]], on="train_id", how="left")
    p["date"] = p["onset_ts"].dt.normalize()
    p["hour"] = p["onset_ts"].dt.hour
    p["onset_tod_h"] = (p["onset_ts"] - p["date"]).dt.total_seconds() / 3600
    seq = stations["seq_map"]
    p["seq_from"] = [seq.get(k, np.nan) for k in zip(p["route_id"], p["from_station"])]
    p["seq_to"] = [seq.get(k, np.nan) for k in zip(p["route_id"], p["to_station"])]
    check("incident location not on the train's route",
          int((p["seq_from"].isna() | (p["location_type"].eq("segment") & p["seq_to"].isna())).sum()))
    p["is_terminal_station"] = p["location_type"].eq("station") & p.apply(
        lambda r: r["from_station"] in stations["endpoints"][r["route_id"]], axis=1)

    # link to movement events of the same train (only train-days with incidents)
    keys = set(zip(p["train_id"], p["date"]))
    o = ops[ops["train_id"].isin(p["train_id"].unique())].copy()
    o["train_id"] = o["train_id"].astype(str)
    o["station"] = o["station"].astype(str)
    o["event_description"] = o["event_description"].astype(str)
    o["date"] = o["timestamp"].dt.normalize()
    o = o[[k in keys for k in zip(o["train_id"], o["date"])]].sort_values("timestamp")
    prev = pd.merge_asof(p[["incident_id", "train_id", "onset_ts"]].sort_values("onset_ts"),
                         o.rename(columns={"timestamp": "prev_ts", "station": "prev_loc",
                                           "event_description": "prev_event"})[["train_id", "prev_ts", "prev_loc", "prev_event"]],
                         left_on="onset_ts", right_on="prev_ts", by="train_id", direction="backward")
    nxt_ev = pd.merge_asof(p[["incident_id", "train_id", "recovery_ts"]].sort_values("recovery_ts"),
                           o.rename(columns={"timestamp": "resume_ts", "station": "resume_loc",
                                             "event_description": "resume_event"})[["train_id", "resume_ts", "resume_loc", "resume_event"]],
                           left_on="recovery_ts", right_on="resume_ts", by="train_id", direction="forward")
    p = p.merge(prev.drop(columns=["train_id", "onset_ts"]), on="incident_id").merge(
        nxt_ev.drop(columns=["train_id", "recovery_ts"]), on="incident_id")
    p["hold_after_recovery_s"] = (p["resume_ts"] - p["recovery_ts"]).dt.total_seconds()

    # consistency of incident context with the movement grammar
    seg_i = p["location_type"].eq("segment")
    check("segment incident: previous event is not a departure from the segment's first station",
          int((seg_i & ~(p["prev_event"].isin(DEP_EVENTS) & p["prev_loc"].eq(p["from_station"]))).sum()))
    check("segment incident: next event is not DEPARTED_BREAKDOWN_POINT at the same label",
          int((seg_i & ~(p["resume_event"].eq("DEPARTED_BREAKDOWN_POINT") & p["resume_loc"].eq(p["location"]))).sum()))
    check("station incident: previous event is not ARRIVED at that station",
          int((~seg_i & ~(p["prev_event"].eq("ARRIVED") & p["prev_loc"].eq(p["from_station"]))).sum()))
    check("station incident: next event is not a departure from that station",
          int((~seg_i & ~(p["resume_event"].isin(DEP_EVENTS) & p["resume_loc"].eq(p["from_station"]))).sum()))
    check("incidents with no movement event after recovery that day", int(p["resume_ts"].isna().sum()))
    check("hold_after_recovery_s < 0", int((p["hold_after_recovery_s"] < 0).sum()))
    log(f"- hold_after_recovery_s (resume movement minus RECOVERED): "
        f"==0 in {(p['hold_after_recovery_s'] == 0).sum()}, >0 in {(p['hold_after_recovery_s'] > 0).sum()} incidents")
    o_mid = o.merge(p[["train_id", "onset_ts", "recovery_ts"]], on="train_id")
    check("movement events of the train strictly between onset and recovery",
          int(((o_mid["timestamp"] > o_mid["onset_ts"]) & (o_mid["timestamp"] < o_mid["recovery_ts"])).sum()))
    n_dbp = int((ops["event_description"] == "DEPARTED_BREAKDOWN_POINT").sum())
    check("DEPARTED_BREAKDOWN_POINT rows not matched to a segment incident",
          n_dbp - int((seg_i & p["resume_event"].eq("DEPARTED_BREAKDOWN_POINT")).sum()))

    # link to traversal (trip, direction, affected segment travel time)
    tv = t[["train_id", "dep_ts", "trip_key", "trip_no", "direction", "segment", "travel_s",
            "excess_travel_s", "dwell_s"]]
    p["trav_dep_ts"] = np.where(seg_i, p["prev_ts"], p["resume_ts"])
    p["trav_dep_ts"] = pd.to_datetime(p["trav_dep_ts"])
    p = p.merge(tv.rename(columns={"dep_ts": "trav_dep_ts", "segment": "trav_segment"}),
                on=["train_id", "trav_dep_ts"], how="left")
    check("incidents not linked to a traversal", int(p["trip_key"].isna().sum()))
    # for segment incidents the affected traversal is the segment; for station incidents
    # the travel/excess columns describe the segment departed after the dwell
    p = p.rename(columns={"travel_s": "linked_travel_s", "excess_travel_s": "linked_excess_travel_s",
                          "dwell_s": "linked_dwell_s"})

    # misc descriptors
    p = p.sort_values("onset_ts").reset_index(drop=True)
    p["incident_no_for_train"] = p.groupby("train_id").cumcount() + 1
    p["n_incidents_train_day"] = p.groupby(["train_id", "date"])["incident_id"].transform("size")
    st_ = p["onset_ts"].to_numpy()
    en_ = p["recovery_ts"].to_numpy()
    p["n_overlapping_incidents"] = [int(((st_ < e) & (en_ > s)).sum() - 1) for s, e in zip(st_, en_)]

    section("3b. Incident summary")
    log(f"- incidents: {len(p)} (segment {seg_i.sum()}, station {(~seg_i).sum()}, "
        f"of which at a route terminal {int(p['is_terminal_station'].sum())})")
    d = p["duration_s"]
    log(f"- duration_s: min {d.min():.0f}, median {d.median():.0f}, mean {d.mean():.1f}, "
        f"max {d.max():.0f}; by location type median "
        f"{p.groupby('location_type')['duration_s'].median().to_dict()}")
    log(f"- incidents per train: {p.groupby('train_id').size().value_counts().sort_index().to_dict()} "
        f"(count -> n trains; {len(trains) - p['train_id'].nunique()} trains with none)")
    log(f"- train-days with >1 incident: {(p.groupby(['train_id', 'date']).size() > 1).sum()}")
    log(f"- incidents overlapping in time with another incident: {(p['n_overlapping_incidents'] > 0).sum()}")
    per_date = p.groupby("date").size()
    log(f"- dates with >=1 incident: {len(per_date)} of {len(EXPECTED_DATES)}; incidents per incident-date "
        f"(n incidents -> n dates): {per_date.value_counts().sort_index().to_dict()}; busiest dates: "
        + ", ".join(f"{d.date()} ({n})" for d, n in per_date.sort_values(ascending=False).head(5).items()))
    FACTS.update(n_incidents=len(p), n_seg=int(seg_i.sum()), n_station=int((~seg_i).sum()),
                 n_overlap=int((p["n_overlapping_incidents"] > 0).sum()), max_per_date=int(per_date.max()),
                 dur_min=float(d.min()), dur_max=float(d.max()),
                 n_terminal=int(p["is_terminal_station"].sum()),
                 all_zero_hold=bool((p["hold_after_recovery_s"] == 0).all()))
    log("By line/route:")
    table(pd.crosstab([p["line_id"], p["route_id"]], p["location_type"], margins=True))
    log("By train type:")
    table(pd.crosstab(p["train_type"], p["location_type"], margins=True))
    log("By onset hour:")
    table(p["hour"].value_counts().sort_index().rename("n").to_frame().T, index=False)
    log("By month:")
    table(p["date"].dt.month.value_counts().sort_index().rename("n").to_frame().T, index=False)

    cols = ["incident_id", "train_id", "line_id", "route_id", "train_type", "batch_number", "date",
            "hour", "onset_tod_h", "onset_ts", "recovery_ts", "duration_s", "location",
            "location_type", "from_station", "to_station", "seq_from", "seq_to",
            "is_terminal_station", "prev_event", "prev_ts", "resume_event", "resume_ts",
            "hold_after_recovery_s", "trip_key", "trip_no", "direction", "trav_segment",
            "linked_travel_s", "linked_excess_travel_s", "linked_dwell_s", "incident_no_for_train",
            "n_incidents_train_day", "n_overlapping_incidents"]
    p = p[cols]
    for c in ["seq_from", "seq_to", "trip_key", "trip_no"]:
        p[c] = p[c].astype("Int64")   # integer with NA (seq_to blank for station incidents)
    out = p.copy()
    out["date"] = out["date"].dt.strftime("%Y-%m-%d")
    out.to_csv(DERIVED / "breakdowns.csv", index=False, encoding="utf-8")
    return p


