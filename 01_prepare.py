"""01_prepare.py -- data audit and derived tables for the Shanghai Metro project.

Run from anywhere:  python3 src/01_prepare.py

Steps
  0. load raw CSVs (normal_operations cached as pickle in data_derived/)
  1. audit every file (counts, types, missing, duplicates, coverage, integrity,
     event codes, ordering, anomalies) -- anomalies are counted, never dropped
  2. traversals.pkl            per-traversal travel / dwell times (+ trip validation)
     segment_baseline.csv      median travel time per directed segment x route
  3. breakdowns.csv            one row per BREAKDOWN -> RECOVERED incident
  4. train_day.csv             exposure per train x service date
  5. train_day_cleaning.csv    cleaning features at start of each train-day

All findings are printed and written to notes/01_data_audit.md (rewritten after
every step so partial progress survives an interruption).
"""

from __future__ import annotations

import re
import time
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
DERIVED = ROOT / "data_derived"
NOTES = ROOT / "notes"
DERIVED.mkdir(exist_ok=True)
NOTES.mkdir(exist_ok=True)

ENC = "utf-8-sig"
TS_FMT = "%Y-%m-%d %H:%M:%S"
T0 = time.time()

# Service calendar given in the project guide: weekdays 2026-03-02..2026-07-31
# minus the listed weekday holidays (expected: 105 dates).
HOLIDAYS = pd.to_datetime(["2026-04-06", "2026-05-01", "2026-05-04", "2026-05-05", "2026-06-19"])
EXPECTED_DATES = pd.bdate_range("2026-03-02", "2026-07-31").difference(HOLIDAYS)

OPS_EVENTS = {"DEPARTED_ORIGIN", "ARRIVED", "DEPARTED", "DEPARTED_BREAKDOWN_POINT"}
DEP_EVENTS = ["DEPARTED_ORIGIN", "DEPARTED"]
BR_EVENTS = {"BREAKDOWN", "RECOVERED"}
VALID_LINE_ROUTES = {("2", "2"), ("8", "8"), ("10", "10"), ("10", "10B"), ("12", "12")}
SEG_RE = re.compile(r"^(S\d{3}) -> (S\d{3})$")
STATION_RE = re.compile(r"^S\d{3}$")


# --------------------------------------------------------------------------
# report helpers: every finding goes both to stdout and to the markdown notes
# --------------------------------------------------------------------------
REPORT: list[str] = []
FACTS: dict = {}  # key numbers reused in the closing 'data quirks' section


def log(msg: str = "") -> None:
    """Print a line and keep it for the audit notes."""
    print(msg, flush=True)
    REPORT.append(msg)


def section(title: str) -> None:
    log("")
    log(f"## {title}")
    log(f"_(elapsed {time.time() - T0:.1f}s)_")
    log("")


def _fmt(v) -> str:
    if isinstance(v, (float, np.floating)):
        if pd.isna(v):
            return ""
        if float(v).is_integer():
            return f"{int(v)}"
        return f"{v:.0f}" if abs(v) >= 1e4 else f"{v:.4g}"
    return str(v)


def table(df: pd.DataFrame | pd.Series, index: bool = True) -> None:
    """Log a small frame as a markdown table (no tabulate dependency)."""
    if isinstance(df, pd.Series):
        df = df.to_frame()
    d = df.reset_index() if index else df
    cols = [str(c) for c in d.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in d.itertuples(index=False):
        lines.append("| " + " | ".join(_fmt(v) for v in row) + " |")
    log("\n".join(lines))
    log("")


def check(label: str, n: int, expect_zero: bool = True) -> int:
    """Log an anomaly counter; mark non-zero counts that were expected to be zero."""
    flag = " **<-- anomaly**" if (expect_zero and n) else ""
    if expect_zero and n:
        FACTS.setdefault("anomalies", []).append(f"{label}: {n}")
    log(f"- {label}: {n}{flag}")
    return n


def flush_notes() -> None:
    """Write the notes file now (called after every step so progress is durable)."""
    header = (
        "# 01 Data audit and derived data\n\n"
        "Generated by `src/01_prepare.py`; re-run the script to regenerate. "
        "Numbers below are computed, not hand-typed.\n"
    )
    (NOTES / "01_data_audit.md").write_text(header + "\n".join(REPORT) + "\n", encoding="utf-8")


def to_ts(s: pd.Series) -> pd.Series:
    """Strict timestamp parse; invalid strings become NaT (and are counted by caller)."""
    return pd.to_datetime(s, format=TS_FMT, errors="coerce")


