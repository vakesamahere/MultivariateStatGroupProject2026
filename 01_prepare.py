def build_cleaning(cl: pd.DataFrame, td: pd.DataFrame, trains: pd.DataFrame) -> pd.DataFrame:
    section("5a. cleaning_records audit")
    cl = cl.copy()
    cl["completed_at"] = to_ts(cl["completed_at"])
    check("unparseable completed_at", int(cl["completed_at"].isna().sum()))
    check("cleaning records for trains not in train_information", int((~cl["train_id"].isin(trains["train_id"])).sum()))
    check("trains with no cleaning record", int((~trains["train_id"].isin(cl["train_id"])).sum()))
    check("duplicate (train, completed_at)", int(cl.duplicated(["train_id", "completed_at"]).sum()))
    for c, allowed in [("cleaning_type", {"ROUTINE", "DEEP"}), ("cleaning_team", {"CT1", "CT2", "CT3", "CT4"}),
                       ("cleaning_product_code", {"CP1", "CP2", "CP3"})]:
        check(f"{c} values outside {sorted(allowed)}", int((~cl[c].isin(allowed)).sum()))
        log(f"  - {c}: {cl[c].value_counts().sort_index().to_dict()}")
    cl["date"] = cl["completed_at"].dt.normalize()
    per = cl.groupby(["train_id", "date"]).size()
    log(f"- records per train-date: {per.value_counts().to_dict()}; train-dates with records: {len(per)}")
    tod = cl["completed_at"] - cl["date"]
    log(f"- completion time of day: {tod.min()} .. {tod.max()}")
    m = cl.merge(td[["train_id", "date", "first_event_ts", "last_event_ts"]], on=["train_id", "date"], how="left")
    check("cleaning completed on a date the train did not operate", int(m["first_event_ts"].isna().sum()))
    check("cleaning completed during the train's service window (first..last event)",
          int(((m["completed_at"] >= m["first_event_ts"]) & (m["completed_at"] <= m["last_event_ts"])).sum()))
    gap_h = (m["first_event_ts"] - m["completed_at"]).dt.total_seconds() / 3600
    log(f"- hours from same-day cleaning completion to first departure: min {gap_h.min():.2f}, "
        f"median {gap_h.median():.2f}, max {gap_h.max():.2f}")

    section("5b. Cleaning cadence and assignment regularity")
    cl = cl.sort_values(["train_id", "completed_at"]).reset_index(drop=True)
    deep = cl[cl["cleaning_type"] == "DEEP"].copy()
    date_idx = pd.Series(np.arange(len(EXPECTED_DATES)), index=EXPECTED_DATES)
    deep["svc_idx"] = deep["date"].map(date_idx)
    deep["svc_days_gap"] = deep.groupby("train_id")["svc_idx"].diff()
    deep["cal_days_gap"] = deep.groupby("train_id")["date"].diff().dt.days
    log(f"- DEEP share {(cl['cleaning_type'] == 'DEEP').mean():.3f}; DEEP per train: "
        f"{deep.groupby('train_id').size().describe()[['min', '50%', 'max']].to_dict()}")
    log(f"- gap between consecutive DEEP cleanings in service days: "
        f"{deep['svc_days_gap'].value_counts().sort_index().to_dict()}")
    log(f"- gap in calendar days: {deep['cal_days_gap'].value_counts().sort_index().to_dict()}")
    # regularity check: a fixed cycle would give one dominant gap; an independent daily draw
    # with probability p gives a geometric gap with P(gap=1) ~= p and mean ~= 1/p
    p_deep = float((cl["cleaning_type"] == "DEEP").mean())
    g = deep["svc_days_gap"].dropna()
    per_train_cv = deep.groupby("train_id")["svc_days_gap"].agg(lambda x: x.std() / x.mean())
    log(f"- DEEP gap (service days): mean {g.mean():.2f} vs 1/p = {1 / p_deep:.2f}; P(gap=1) {(g == 1).mean():.3f} "
        f"vs p = {p_deep:.3f}; per-train coefficient of variation of gaps median {per_train_cv.median():.2f} "
        f"(geometric ~ {np.sqrt(1 - p_deep):.2f}; fixed cycle = 0)")
    share_deep_tr = cl.groupby("train_id")["cleaning_type"].apply(lambda s: (s == "DEEP").mean())
    log(f"- per-train DEEP share: min {share_deep_tr.min():.3f}, median {share_deep_tr.median():.3f}, "
        f"max {share_deep_tr.max():.3f}, sd across trains {share_deep_tr.std():.3f} vs binomial sd "
        f"{np.sqrt(p_deep * (1 - p_deep) / 105):.3f} expected if all trains shared one DEEP rate")
    FACTS.update(p_deep=p_deep, deep_gap_mean=float(g.mean()), deep_cv=float(per_train_cv.median()),
                 deep_share_min=float(share_deep_tr.min()), deep_share_max=float(share_deep_tr.max()))
    fd = deep.groupby("train_id")["svc_idx"].min()
    log(f"- first DEEP cleaning at service-day index (0 = 2026-03-02): {fd.value_counts().sort_index().to_dict()}")
    nu = cl.groupby("train_id")[["cleaning_team", "cleaning_product_code"]].nunique()
    log(f"- distinct teams per train: {nu['cleaning_team'].value_counts().sort_index().to_dict()}; "
        f"distinct products per train: {nu['cleaning_product_code'].value_counts().sort_index().to_dict()}")
    chg = cl.groupby("train_id")["cleaning_team"].apply(lambda s: int((s != s.shift()).sum() - 1))
    log(f"- team changes between consecutive cleanings per train: median {chg.median():.0f}, "
        f"max {chg.max()} (out of 104 transitions; independent uniform assignment over 4 teams "
        f"would give ~{104 * 0.75:.0f})")
    FACTS["team_changes_median"] = float(chg.median())
    log("Team x product (all records):")
    table(pd.crosstab(cl["cleaning_team"], cl["cleaning_product_code"], margins=True))
    log("Cleaning type by team:")
    table(pd.crosstab(cl["cleaning_team"], cl["cleaning_type"], margins=True))
    ctl = cl.merge(trains[["train_id", "line_id", "route_id"]], on="train_id")
    log("Team by line:")
    table(pd.crosstab(ctl["line_id"], ctl["cleaning_team"]))

    section("5c. Train-day cleaning features")
    base = td[["train_id", "date", "first_event_ts"]].sort_values("first_event_ts")
    out = base.copy()
    specs = [("any", cl), ("routine", cl[cl["cleaning_type"] == "ROUTINE"]), ("deep", deep)]
    for tag, src in specs:
        s = src[["train_id", "completed_at", "cleaning_type", "cleaning_team", "cleaning_product_code"]]
        s = s.rename(columns={"completed_at": f"last_{tag}_clean_ts", "cleaning_type": f"last_{tag}_type",
                              "cleaning_team": f"last_{tag}_team", "cleaning_product_code": f"last_{tag}_product"})
        s = s.sort_values(f"last_{tag}_clean_ts")
        # strictly before first departure (cleaning cannot happen during service)
        out = pd.merge_asof(out, s, left_on="first_event_ts", right_on=f"last_{tag}_clean_ts",
                            by="train_id", direction="backward", allow_exact_matches=False)
        out[f"hours_since_{tag}_clean"] = (out["first_event_ts"] - out[f"last_{tag}_clean_ts"]).dt.total_seconds() / 3600
        out[f"svc_days_since_{tag}_clean"] = out["date"].map(date_idx) - out[f"last_{tag}_clean_ts"].dt.normalize().map(date_idx)
    out = out.rename(columns={"last_any_type": "last_clean_type", "last_any_team": "last_clean_team",
                              "last_any_product": "last_clean_product"})
    out["cleaned_same_morning"] = out["svc_days_since_any_clean"].eq(0)
    # running count of DEEP cleanings completed before this train-day's first departure
    k = deep.assign(n_deep_cleans_to_date=deep.groupby("train_id").cumcount() + 1)
    out = pd.merge_asof(out, k[["train_id", "completed_at", "n_deep_cleans_to_date"]].sort_values("completed_at"),
                        left_on="first_event_ts", right_on="completed_at", by="train_id",
                        direction="backward", allow_exact_matches=False).drop(columns="completed_at")
    out["n_deep_cleans_to_date"] = out["n_deep_cleans_to_date"].fillna(0).astype(int)
    keep = ["train_id", "date", "first_event_ts",
            "last_any_clean_ts", "hours_since_any_clean", "svc_days_since_any_clean",
            "last_clean_type", "last_clean_team", "last_clean_product", "cleaned_same_morning",
            "last_routine_clean_ts", "hours_since_routine_clean", "svc_days_since_routine_clean",
            "last_routine_team", "last_routine_product",
            "last_deep_clean_ts", "hours_since_deep_clean", "svc_days_since_deep_clean",
            "last_deep_team", "last_deep_product", "n_deep_cleans_to_date"]
    out = out[keep].sort_values(["train_id", "date"]).reset_index(drop=True)
    check("train-days with no prior cleaning of any type (left-censored)",
          int(out["last_any_clean_ts"].isna().sum()), expect_zero=False)
    check("train-days with no prior DEEP cleaning in the data (left-censored)",
          int(out["last_deep_clean_ts"].isna().sum()), expect_zero=False)
    check("train-days not cleaned the same morning", int((~out["cleaned_same_morning"]).sum()), expect_zero=False)
    log(f"- hours_since_any_clean: median {out['hours_since_any_clean'].median():.2f}, "
        f"range {out['hours_since_any_clean'].min():.2f} .. {out['hours_since_any_clean'].max():.2f}")
    FACTS.update(h_since_min=float(out["hours_since_any_clean"].min()),
                 h_since_max=float(out["hours_since_any_clean"].max()))
    log(f"- svc_days_since_deep_clean distribution: "
        f"{out['svc_days_since_deep_clean'].value_counts().sort_index().to_dict()}")
    log(f"- last_clean_type at start of service: {out['last_clean_type'].value_counts().to_dict()}")
    o = out.copy()
    o["date"] = o["date"].dt.strftime("%Y-%m-%d")
    o.to_csv(DERIVED / "train_day_cleaning.csv", index=False, encoding="utf-8")
    return out


