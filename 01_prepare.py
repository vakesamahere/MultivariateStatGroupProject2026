# --------------------------------------------------------------------------
def build_traversals(ops: pd.DataFrame, trains: pd.DataFrame, stations: dict) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Parse each train's event stream into segment traversals.

    A traversal is one departure (DEPARTED_ORIGIN or DEPARTED) followed by zero or
    more DEPARTED_BREAKDOWN_POINT rows and exactly one ARRIVED. Rows are grouped by
    a running departure counter after sorting by (train, time).
    """
    section("2a. Event grammar and station continuity (per train, time-ordered)")
    s = ops.sort_values(["train_id", "timestamp"], kind="stable").reset_index(drop=True)
    train = s["train_id"].astype(str).to_numpy()
    ev = s["event_description"].astype(str).to_numpy()
    loc = s["station"].astype(str).to_numpy()
    ts = s["timestamp"].to_numpy()
    date = s["timestamp"].dt.normalize().to_numpy()

    # transition table (previous event -> event) within train
    same_tr = np.r_[False, train[1:] == train[:-1]]
    same_day = same_tr & np.r_[False, date[1:] == date[:-1]]
    prev_ev = np.where(same_day, np.r_[["(start)"], ev[:-1]], "(start of day)")
    trans = pd.crosstab(pd.Series(prev_ev, name="previous event (same train-day)"),
                        pd.Series(ev, name="event"))
    table(trans)
    allowed = {("(start of day)", "DEPARTED_ORIGIN"), ("DEPARTED_ORIGIN", "ARRIVED"),
               ("DEPARTED_ORIGIN", "DEPARTED_BREAKDOWN_POINT"), ("DEPARTED", "ARRIVED"),
               ("DEPARTED", "DEPARTED_BREAKDOWN_POINT"), ("DEPARTED_BREAKDOWN_POINT", "ARRIVED"),
               ("DEPARTED_BREAKDOWN_POINT", "DEPARTED_BREAKDOWN_POINT"),
               ("ARRIVED", "DEPARTED"), ("ARRIVED", "DEPARTED_ORIGIN")}
    bad = sum(int(trans.loc[a, b]) for a in trans.index for b in trans.columns
              if trans.loc[a, b] and (a, b) not in allowed)
    check("transitions outside the expected grammar", bad)
    last_of_day = np.r_[~same_day[1:], True]
    check("train-days whose last event is not ARRIVED", int((last_of_day & (ev != "ARRIVED")).sum()))

    # group rows into traversals
    is_dep = np.isin(ev, DEP_EVENTS)
    tidx = np.cumsum(is_dep) - 1
    first_of_train = ~same_tr
    check("trains whose first event is not a departure", int((first_of_train & ~is_dep).sum()))
    n_trav = int(is_dep.sum())
    n_arr = np.bincount(tidx[ev == "ARRIVED"], minlength=n_trav)
    n_dbp = np.bincount(tidx[ev == "DEPARTED_BREAKDOWN_POINT"], minlength=n_trav)
    check("traversals without exactly one ARRIVED", int((n_arr != 1).sum()))

    dep_pos = np.flatnonzero(is_dep)
    arr_pos = np.flatnonzero(ev == "ARRIVED")
    arr_of = np.full(n_trav, -1)
    arr_of[tidx[arr_pos]] = arr_pos
    ok = arr_of >= 0
    t = pd.DataFrame({
        "train_id": train[dep_pos], "date": date[dep_pos], "dep_event": ev[dep_pos],
        "from_station": loc[dep_pos], "dep_ts": ts[dep_pos],
    })
    t["to_station"] = np.where(ok, loc[np.where(ok, arr_of, 0)], None)
    t["arr_ts"] = pd.Series(np.where(ok, ts[np.where(ok, arr_of, 0)], np.datetime64("NaT")))
    t["n_bd_on_segment"] = n_dbp
    check("traversal arrival on a different date than departure",
          int((t["arr_ts"].dt.normalize() != t["date"]).sum()))

    # DEPARTED_BREAKDOWN_POINT label must equal 'from -> to' of its traversal
    dbp_pos = np.flatnonzero(ev == "DEPARTED_BREAKDOWN_POINT")
    exp_lbl = t["from_station"].to_numpy()[tidx[dbp_pos]] + " -> " + t["to_station"].astype(str).to_numpy()[tidx[dbp_pos]]
    check("DEPARTED_BREAKDOWN_POINT label != 'departure station -> next arrival'",
          int((exp_lbl != loc[dbp_pos]).sum()))

    # travel and dwell
    t["travel_s"] = (t["arr_ts"] - t["dep_ts"]).dt.total_seconds()
    prev_same_day = (t["train_id"].eq(t["train_id"].shift()) & t["date"].eq(t["date"].shift()))
    prev_arr_st = t["to_station"].shift()
    gap = (t["dep_ts"] - t["arr_ts"].shift()).dt.total_seconds()
    check("departure station != previous arrival station (same train-day)",
          int((prev_same_day & (t["from_station"] != prev_arr_st)).sum()))
    is_mid = t["dep_event"].eq("DEPARTED")
    t["dwell_s"] = np.where(is_mid & prev_same_day, gap, np.nan)
    t["turnaround_s"] = np.where(~is_mid & prev_same_day, gap, np.nan)
    check("DEPARTED with no preceding arrival that day", int((is_mid & ~prev_same_day).sum()))
    # overnight positioning: does the first trip of a day start where the train ended?
    prev_same_tr = t["train_id"].eq(t["train_id"].shift())
    newday = prev_same_tr & ~prev_same_day
    log(f"- first departure of day at the station where the train ended the previous day: "
        f"{(t.loc[newday, 'from_station'] == prev_arr_st[newday]).sum()} of {int(newday.sum())}")

    # trips: running count of DEPARTED_ORIGIN
    t["trip_key"] = (t["dep_event"] == "DEPARTED_ORIGIN").cumsum() - 1
    t["trip_no"] = t["trip_key"] - t.groupby(["train_id", "date"])["trip_key"].transform("min") + 1

    # route validation: route comes from the train's attributes
    t = t.merge(trains[["train_id", "line_id", "route_id"]], on="train_id", how="left")
    seq = stations["seq_map"]
    t["seq_from"] = [seq.get(k, np.nan) for k in zip(t["route_id"], t["from_station"])]
    t["seq_to"] = [seq.get(k, np.nan) for k in zip(t["route_id"], t["to_station"])]
    step = t["seq_to"] - t["seq_from"]
    section("2b. Segment validation against station_information adjacency")
    check("traversal stations not on the train's route",
          int((t["seq_from"].isna() | t["seq_to"].isna()).sum()))
    check("traversals between non-adjacent stations (|seq step| != 1)", int((step.abs() != 1).sum()))
    t["direction"] = np.select([step == 1, step == -1], ["asc", "desc"], "invalid")
    t["segment"] = t["from_station"] + " -> " + t["to_station"]
    log(f"- traversals: {len(t):,}; directed (route, segment) pairs observed: "
        f"{t.groupby(['route_id', 'segment']).ngroups}; expected 2*(n_stations-1) per route = "
        f"{sum(2 * (n - 1) for n in stations['route_len'].values())}")

    # trip validation
    trips = t.groupby("trip_key").agg(
        train_id=("train_id", "first"), route_id=("route_id", "first"), date=("date", "first"),
        origin=("from_station", "first"), terminus=("to_station", "last"),
        n_trav=("segment", "size"), n_dir=("direction", "nunique"),
        start=("dep_ts", "first"), end=("arr_ts", "last"))
    ends = trips["route_id"].map(stations["endpoints"])
    full = [({o, d} == set(e)) for o, d, e in zip(trips["origin"], trips["terminus"], ends)]
    trips["complete"] = np.array(full) & (trips["n_trav"] == trips["route_id"].map(stations["route_len"]) - 1) \
        & (trips["n_dir"] == 1)
    log(f"- one-way trips: {len(trips):,}")
    check("trips not running endpoint-to-endpoint over the full route in one direction",
          int((~trips["complete"]).sum()))
    t["hour"] = t["dep_ts"].dt.hour

    # impossible / extreme times
    section("2c. Travel and dwell time distributions")
    check("travel_s <= 0", int((t["travel_s"] <= 0).sum()))
    check("dwell_s <= 0", int((t["dwell_s"] <= 0).sum()))
    check("turnaround_s <= 0", int((t["turnaround_s"] <= 0).sum()))
    q = [0, .01, .5, .99, 1]
    dist = pd.DataFrame({
        "travel_s (no bd on segment)": t.loc[t["n_bd_on_segment"] == 0, "travel_s"].quantile(q),
        "travel_s (bd on segment)": t.loc[t["n_bd_on_segment"] > 0, "travel_s"].quantile(q),
        "dwell_s": t["dwell_s"].quantile(q), "turnaround_s": t["turnaround_s"].quantile(q)})
    dist.index = ["min", "p1", "median", "p99", "max"]
    table(dist)
    log(f"- share of travel times that are multiples of 30 s: {(t['travel_s'] % 30 == 0).mean():.4%}; "
        f"dwell_s value counts (top): {t['dwell_s'].value_counts().head(4).to_dict()}")
    return t, trips


def build_baseline(t: pd.DataFrame) -> pd.DataFrame:
    """Median travel time per directed segment x route; adds t['excess_travel_s'] in place."""
    # baseline: median travel time per (route, directed segment), excluding traversals
    # in which the train itself broke down on that segment
    clean = t[t["n_bd_on_segment"] == 0]
    base = clean.groupby(["route_id", "segment"]).agg(
        line_id=("line_id", "first"), from_station=("from_station", "first"),
        to_station=("to_station", "first"), direction=("direction", "first"),
        n=("travel_s", "size"), median_travel_s=("travel_s", "median"),
        mean_travel_s=("travel_s", "mean"), p10_travel_s=("travel_s", lambda x: x.quantile(.1)),
        p90_travel_s=("travel_s", lambda x: x.quantile(.9)), min_travel_s=("travel_s", "min"),
        max_travel_s=("travel_s", "max")).reset_index()
    base["median_dwell_s_at_to_station"] = base.merge(
        t.groupby(["route_id", "from_station", "direction"])["dwell_s"].median().rename("d").reset_index(),
        left_on=["route_id", "to_station", "direction"],
        right_on=["route_id", "from_station", "direction"], how="left")["d"].to_numpy()
    base.to_csv(DERIVED / "segment_baseline.csv", index=False, encoding="utf-8")
    t["excess_travel_s"] = t["travel_s"] - t.merge(base[["route_id", "segment", "median_travel_s"]],
                                                   on=["route_id", "segment"], how="left")["median_travel_s"].to_numpy()

    section("2d. Segment baseline")
    log(f"- segment_baseline.csv: {len(base)} (route, directed segment) rows; traversals per row "
        f"min {base['n'].min()}, median {base['n'].median():.0f}")
    log(f"- median travel_s across segments: min {base['median_travel_s'].min()}, "
        f"median {base['median_travel_s'].median()}, max {base['median_travel_s'].max()}")
    # shared track (S003-S004 on routes 2 and 10; Longxi Rd..Jilong Rd on 10 and 10B)
    sh = base.groupby("segment").filter(lambda g: len(g) > 1)
    dis = sh.groupby("segment")["median_travel_s"].nunique()
    log(f"- directed segments used by >1 route: {sh['segment'].nunique()}; with differing medians "
        f"across routes: {(dis > 1).sum()}")
    diff = sh[sh["segment"].isin(dis[dis > 1].index)]
    FACTS["shared_diff"] = "; ".join(f"{r.segment} route {r.route_id}: {r.median_travel_s:.0f} s"
                                     for r in diff.itertuples())
    if len(diff):
        log(f"  - differing: {FACTS['shared_diff']}")
    ex = t.loc[t["n_bd_on_segment"] == 0, "excess_travel_s"]
    log(f"- excess travel vs baseline (no own breakdown on segment): >0 s in {(ex > 0).mean():.2%} of "
        f"traversals, >60 s in {(ex > 60).sum():,}, >300 s in {(ex > 300).sum():,}")
    log("")
    return base


def save_traversals(t: pd.DataFrame, bd: pd.DataFrame) -> None:
    """Attach station-breakdown flags and save the per-traversal pickle."""
    section("3c. traversals.pkl (saved after incidents are linked)")
    # flag traversals whose departure station hosted a station breakdown during the dwell
    st_bd = bd[bd["location_type"] == "station"][["train_id", "resume_ts"]].assign(bd_at_from_station=True)
    t = t.merge(st_bd, left_on=["train_id", "dep_ts"], right_on=["train_id", "resume_ts"], how="left")
    t["bd_at_from_station"] = t["bd_at_from_station"].astype("boolean").fillna(False).astype(bool)
    t = t.drop(columns="resume_ts")

    cols = ["train_id", "line_id", "route_id", "date", "trip_key", "trip_no", "direction", "segment",
            "from_station", "to_station", "dep_event", "dep_ts", "arr_ts", "hour", "travel_s",
            "dwell_s", "turnaround_s", "excess_travel_s", "n_bd_on_segment", "bd_at_from_station"]
    out = t[cols].copy()
    for c in ["train_id", "line_id", "route_id", "direction", "segment", "from_station",
              "to_station", "dep_event"]:
        out[c] = out[c].astype("category")
    # compact dtypes: all durations are whole seconds well below float32 precision limits
    out = out.astype({"trip_key": "int32", "trip_no": "int8", "hour": "int8", "n_bd_on_segment": "int8",
                      "travel_s": "float32", "dwell_s": "float32", "turnaround_s": "float32",
                      "excess_travel_s": "float32"})
    out.to_pickle(DERIVED / "traversals.pkl")
    log(f"- traversals.pkl saved: {len(out):,} rows; with own segment breakdown "
        f"{int((out['n_bd_on_segment'] > 0).sum())}, departing after own station breakdown "
        f"{int(out['bd_at_from_station'].sum())}")
    return t


def delay_footprint(t: pd.DataFrame, bd: pd.DataFrame) -> None:
    """Where do non-baseline movement times occur? (own incident vs knock-on vs none)."""
    section("3d. Delay footprint: are deviations from baseline explained by incidents?")
    bd_dates = set(bd["date"])
    own_seg = t["n_bd_on_segment"] > 0
    ex = t[~own_seg & (t["excess_travel_s"] > 0)]
    check("traversals faster than their segment median", int((t["excess_travel_s"] < 0).sum()))
    log(f"- seg incidents: linked travel_s - duration_s (stop-free remainder vs baseline): median "
        f"{(bd.loc[bd['location_type'] == 'segment', 'linked_excess_travel_s'] - bd.loc[bd['location_type'] == 'segment', 'duration_s']).median():.0f} s")
    st_i = bd["location_type"] == "station"
    log(f"- station incidents: dwell_s - duration_s median "
        f"{(bd.loc[st_i, 'linked_dwell_s'] - bd.loc[st_i, 'duration_s']).median():.0f} s "
        f"(dwell = arrival..onset gap + incident + 0 s hold)")
    log(f"- traversals slower than baseline without an own segment incident: {len(ex):,} on "
        f"{ex['date'].nunique()} dates; share on incident dates: {ex['date'].isin(bd_dates).mean():.1%}")
    # same-line incident window: onset-10 min .. recovery+60 min (Line 10 shares track for 10/10B)
    k = ex[["train_id", "dep_ts", "arr_ts", "line_id", "date"]].merge(
        bd[["line_id", "date", "onset_ts", "recovery_ts"]], on=["line_id", "date"], how="left")
    k["win"] = (k["arr_ts"] >= k["onset_ts"]) & (k["dep_ts"] <= k["recovery_ts"] + pd.Timedelta("60min"))
    share = k.groupby(["train_id", "dep_ts"])["win"].any().mean()
    log(f"- of those, within onset..recovery+60 min of an incident on the same line: {share:.1%}")
    long_dw = t[(t["dwell_s"] > 30) & ~t["bd_at_from_station"]]
    log(f"- dwell_s > 30 s without an own station incident: {len(long_dw):,}; share on incident dates: "
        f"{long_dw['date'].isin(bd_dates).mean():.1%}")
    off = (t["dep_ts"].dt.second % 30 != 0) | (t["arr_ts"].dt.second % 30 != 0)
    first_onset = bd.groupby(["train_id", "date"])["onset_ts"].min().rename("first_onset").reset_index()
    m = t.loc[off, ["train_id", "date", "dep_ts"]].merge(first_onset, on=["train_id", "date"], how="left")
    after_own = int((m["dep_ts"] >= m["first_onset"]).sum())
    log(f"- traversals with an off-grid (not :00/:30) timestamp: {int(off.sum()):,}; after the train's own "
        f"incident that day: {after_own:,}; otherwise (knock-on from other trains): {int(off.sum()) - after_own:,}; "
        f"on incident dates: {t.loc[off, 'date'].isin(bd_dates).mean():.1%}")
    FACTS.update(n_bd_dates=len(bd_dates), n_excess=len(ex), excess_on_bd_dates=float(ex["date"].isin(bd_dates).mean()),
                 excess_in_window=float(share))
    log("")


