def overview(raw: dict[str, pd.DataFrame], ops: pd.DataFrame) -> None:
    section("1a. File overview (rows, missing values, duplicates)")
    log("All small files read with every column as text; blanks -> NA. "
        "normal_operations read with categorical train/station/event.")
    log("")
    rows = []
    for name, df in {**raw, "normal_operations": ops}.items():
        miss = df.isna().sum()
        rows.append({
            "file": name, "rows": len(df), "cols": df.shape[1],
            "missing_cells": int(miss.sum()),
            "cols_with_missing": ", ".join(f"{c}={n}" for c, n in miss.items() if n) or "-",
            "duplicate_rows": int(df.duplicated().sum()),
        })
    table(pd.DataFrame(rows), index=False)
    log("Columns per file:")
    for name, df in {**raw, "normal_operations": ops}.items():
        log(f"- `{name}`: " + ", ".join(f"{c} ({df[c].dtype})" for c in df.columns))
    log("")


def audit_stations(st: pd.DataFrame) -> dict:
    """Validate station_information and build route lookups."""
    section("1b. station_information")
    st = st.copy()
    st["sequence"] = pd.to_numeric(st["sequence"], errors="coerce")
    check("non-numeric sequence", int(st["sequence"].isna().sum()))
    check("duplicate (route_id, station_id)", int(st.duplicated(["route_id", "station_id"]).sum()))
    check("station_id not matching S###", int((~st["station_id"].str.match(STATION_RE)).sum()))
    check("station_id with >1 Chinese/English name",
          int((st.groupby("station_id")[["station_name", "station_name_english"]].nunique() > 1)
              .any(axis=1).sum()))
    check("route with >1 line_id", int((st.groupby("route_id")["line_id"].nunique() > 1).sum()))
    check("invalid (line, route) pairs",
          int((~st[["line_id", "route_id"]].apply(tuple, axis=1).isin(VALID_LINE_ROUTES)).sum()))

    bad_seq = bad_link = bad_blank = 0
    seq_map: dict[tuple[str, str], int] = {}
    endpoints: dict[str, tuple[str, str]] = {}
    route_len: dict[str, int] = {}
    for rid, g in st.sort_values(["route_id", "sequence"]).groupby("route_id"):
        ids = g["station_id"].tolist()
        bad_seq += int(g["sequence"].tolist() != list(range(1, len(g) + 1)))
        exp_prev = [np.nan] + ids[:-1]
        exp_next = ids[1:] + [np.nan]
        for a, b in zip(g["previous_station_id"].tolist() + g["next_station_id"].tolist(),
                        exp_prev + exp_next):
            bad_link += int(not ((pd.isna(a) and pd.isna(b)) or a == b))
        # blanks allowed only at the endpoints
        blanks = g["previous_station_id"].isna() | g["next_station_id"].isna()
        bad_blank += int(blanks.iloc[1:-1].sum())
        seq_map.update({(rid, s): i + 1 for i, s in enumerate(ids)})
        endpoints[rid] = (ids[0], ids[-1])
        route_len[rid] = len(ids)
    check("routes whose sequence is not 1..n", bad_seq)
    check("previous/next ids inconsistent with sequence", bad_link)
    check("blank previous/next at a non-endpoint row", bad_blank)

    summ = st.groupby(["line_id", "route_id"]).agg(n_stations=("station_id", "size")).reset_index()
    summ["endpoints (seq1 / last)"] = summ["route_id"].map(lambda r: " / ".join(endpoints[r]))
    table(summ, index=False)
    n_routes = st.groupby("station_id")["route_id"].nunique()
    log(f"- unique physical stations: {st['station_id'].nunique()} "
        f"(rows {len(st)}); stations on >1 route: {(n_routes > 1).sum()}")
    lines_per = st.groupby("station_id")["line_id"].nunique()
    log(f"- interchange stations (on >1 line): {(lines_per > 1).sum()} -> "
        + ", ".join(sorted(lines_per[lines_per > 1].index)))
    # directed segments that are shared by more than one route
    seg_routes: dict[frozenset, set] = {}
    rows = st.dropna(subset=["next_station_id"])
    for r in rows.itertuples():
        seg_routes.setdefault(frozenset((r.station_id, r.next_station_id)), set()).add(r.route_id)
    shared = {k: v for k, v in seg_routes.items() if len(v) > 1}
    log(f"- undirected track segments: {len(seg_routes)}; shared by >1 route: {len(shared)} "
        f"(route sets: {pd.Series([','.join(sorted(v)) for v in shared.values()]).value_counts().to_dict()})")
    log("")
    return {"st": st, "seq_map": seq_map, "endpoints": endpoints, "route_len": route_len,
            "names": st.drop_duplicates("station_id").set_index("station_id")["station_name_english"]}


def audit_trains(tr: pd.DataFrame) -> pd.DataFrame:
    section("1c. train_information")
    tr = tr.copy()
    tr["service_start_date"] = pd.to_datetime(tr["service_start_date"], format="%Y-%m-%d", errors="coerce")
    check("duplicate train_id", int(tr["train_id"].duplicated().sum()))
    check("train_id not matching T####", int((~tr["train_id"].str.match(r"^T\d{4}$")).sum()))
    check("invalid (line, route) pairs",
          int((~tr[["line_id", "route_id"]].apply(tuple, axis=1).isin(VALID_LINE_ROUTES)).sum()))
    check("unparseable service_start_date", int(tr["service_start_date"].isna().sum()))
    check("service_start_date after first service date (2026-03-02)",
          int((tr["service_start_date"] > EXPECTED_DATES[0]).sum()))
    log(f"- service_start_date range: {tr['service_start_date'].min().date()} .. "
        f"{tr['service_start_date'].max().date()}")
    log("")
    log("Trains per line/route and type:")
    table(pd.crosstab([tr["line_id"], tr["route_id"]], tr["train_type"], margins=True))
    log("Trains per batch and type:")
    table(pd.crosstab(tr["batch_number"], tr["train_type"], margins=True))
    return tr


def audit_weather(temp: pd.DataFrame, rain: pd.DataFrame) -> None:
    section("1d. temperature / rainfall")
    for name, df, col in [("temperature", temp, "mean_temperature_c"), ("rainfall", rain, "rainfall_mm")]:
        dates = pd.to_datetime(df["date"], format="%Y-%m-%d", errors="coerce")
        vals = pd.to_numeric(df[col], errors="coerce")
        log(f"**{name}**: rows {len(df)}")
        check("unparseable dates", int(dates.isna().sum()))
        check("non-numeric values", int(vals.isna().sum()))
        check("duplicate dates", int(dates.duplicated().sum()))
        check("expected service dates missing", len(EXPECTED_DATES.difference(dates)))
        check("dates outside service calendar", len(pd.DatetimeIndex(dates).difference(EXPECTED_DATES)))
        log(f"- {col}: min {vals.min()}, median {vals.median()}, max {vals.max()}"
            + (f", zero days {(vals == 0).sum()}, negative {(vals < 0).sum()}" if name == "rainfall" else ""))
        log("")


def audit_calendar(ops: pd.DataFrame, br: pd.DataFrame, cl: pd.DataFrame) -> None:
    section("1e. Date coverage vs service calendar")
    log(f"Expected service dates from guide: {len(EXPECTED_DATES)} "
        f"({EXPECTED_DATES[0].date()} .. {EXPECTED_DATES[-1].date()}, weekdays minus "
        f"{', '.join(str(h.date()) for h in HOLIDAYS)})")
    log("")
    for name, ts in [("normal_operations", ops["timestamp"]), ("breakdown_recovery", br["timestamp"]),
                     ("cleaning_records", cl["completed_at"])]:
        d = pd.DatetimeIndex(ts.dt.normalize().unique())
        log(f"**{name}**: {len(d)} distinct dates")
        check("dates outside calendar (weekend/holiday/out of range)", len(d.difference(EXPECTED_DATES)))
        check("calendar dates with no records", len(EXPECTED_DATES.difference(d)),
              expect_zero=(name != "breakdown_recovery"))
    log("")


def audit_ops_basic(ops: pd.DataFrame, n_bad_ts: int, trains: pd.DataFrame, stations: dict) -> None:
    section("1f. normal_operations: codes, locations, ordering, service hours")
    log(f"- rows {len(ops):,}; trains {ops['train_id'].nunique()}; distinct location labels "
        f"{ops['station'].nunique()}")
    check("unparseable timestamps", n_bad_ts)
    vc = ops["event_description"].value_counts()
    table(vc)
    check("unknown event codes", int(sum(n for e, n in vc.items() if e not in OPS_EVENTS)))

    # location label vocabulary
    labels = pd.Series(ops["station"].cat.categories)
    is_seg = labels.str.match(SEG_RE)
    is_st = labels.str.match(STATION_RE)
    known = set(stations["st"]["station_id"])
    check("location labels that are neither S### nor 'S### -> S###'", int((~is_seg & ~is_st).sum()))
    check("station labels not in station_information", int((is_st & ~labels.isin(known)).sum()))
    seg_parts = labels[is_seg].str.extract(SEG_RE)
    check("segment labels referencing unknown stations",
          int((~seg_parts[0].isin(known) | ~seg_parts[1].isin(known)).sum()))
    seg_row = ops["station"].isin(labels[is_seg])
    ev = ops["event_description"]
    check("DEPARTED_BREAKDOWN_POINT at a station label (should be segment)",
          int(((ev == "DEPARTED_BREAKDOWN_POINT") & ~seg_row).sum()))
    check("non-breakdown events at a segment label", int(((ev != "DEPARTED_BREAKDOWN_POINT") & seg_row).sum()))

    # trains referential integrity
    ops_tr = set(ops["train_id"].cat.categories[ops["train_id"].cat.codes.unique()])
    info_tr = set(trains["train_id"])
    check("trains in ops not in train_information", len(ops_tr - info_tr))
    check("trains in train_information with no ops", len(info_tr - ops_tr))

    # ordering and ties
    check("rows out of timestamp order (file claims sorted)",
          int((ops["timestamp"].diff() < pd.Timedelta(0)).sum()))
    dup_tt = int(ops.duplicated(["train_id", "timestamp"]).sum())
    check("same train with >1 event in the same second", dup_tt)

    # service hours: data-driven window (guide gives none)
    tod = ops["timestamp"].dt.hour * 3600 + ops["timestamp"].dt.minute * 60 + ops["timestamp"].dt.second
    log(f"- event time-of-day range: {pd.to_timedelta(tod.min(), unit='s')} .. "
        f"{pd.to_timedelta(tod.max(), unit='s')}")
    check("events between 00:00 and 05:00 (night)", int((tod < 5 * 3600).sum()))
    daily = ops.groupby(ops["timestamp"].dt.normalize())["timestamp"].agg(["min", "max"])
    log(f"- per-date first event always {sorted(daily['min'].dt.time.unique())[:3]}; "
        f"last event range {daily['max'].dt.time.min()} .. {daily['max'].dt.time.max()}")
    sec = ops["timestamp"].dt.second
    off = ~sec.isin([0, 30])
    log(f"- timestamps on the :00/:30 second grid: {(~off).mean():.4%}; off-grid events: {off.sum():,} "
        "(attributed to breakdown-induced shifts in section 3d)")
    FACTS["on_grid_share"] = float((~off).mean())
    log("")


