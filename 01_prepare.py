def build_train_day(t: pd.DataFrame, trips: pd.DataFrame, bd: pd.DataFrame, trains: pd.DataFrame) -> pd.DataFrame:
    section("4. Train-day exposure")
    g = t.groupby(["train_id", "date"])
    td = pd.DataFrame({
        "n_trips": g["dep_event"].agg(lambda s: int((s == "DEPARTED_ORIGIN").sum())),
        "n_traversals": g.size(),
        "first_event_ts": g["dep_ts"].min(),
        "last_event_ts": g["arr_ts"].max(),
        "running_s": g["travel_s"].sum(),
        "dwell_s_total": g["dwell_s"].sum(),
        "turnaround_s_total": g["turnaround_s"].sum(),
    }).reset_index()
    tc = trips.groupby(["train_id", "date"])["complete"].sum().rename("n_complete_trips").reset_index()
    td = td.merge(tc, on=["train_id", "date"], how="left")
    td["operating_s"] = (td["last_event_ts"] - td["first_event_ts"]).dt.total_seconds()
    b = bd.groupby(["train_id", "date"]).agg(
        n_breakdowns=("incident_id", "size"),
        n_bd_segment=("location_type", lambda s: int((s == "segment").sum())),
        n_bd_station=("location_type", lambda s: int((s == "station").sum())),
        bd_duration_s=("duration_s", "sum")).reset_index()
    full = pd.MultiIndex.from_product([trains["train_id"], EXPECTED_DATES], names=["train_id", "date"]).to_frame(index=False)
    td = full.merge(td, on=["train_id", "date"], how="left", indicator=True)
    check("train x service-date combinations with no operations", int((td["_merge"] == "left_only").sum()))
    td = td.drop(columns="_merge").merge(b, on=["train_id", "date"], how="left")
    for c in ["n_breakdowns", "n_bd_segment", "n_bd_station", "bd_duration_s"]:
        td[c] = td[c].fillna(0).astype(int)
    td = td.merge(trains[["train_id", "line_id", "route_id", "train_type", "batch_number"]], on="train_id", how="left")
    td["weekday"] = td["date"].dt.day_name()
    check("breakdowns not attributed to a train-day", int(len(bd) - td["n_breakdowns"].sum()))
    log(f"- train-days: {len(td):,} = {td['train_id'].nunique()} trains x {td['date'].nunique()} dates; "
        f"every train operates every service date: {bool(td['n_trips'].notna().all())}")
    log(f"- train-days with >=1 breakdown: {(td['n_breakdowns'] > 0).sum()} "
        f"({(td['n_breakdowns'] > 0).mean():.2%})")
    log("Exposure by route (per train-day):")
    table(td.groupby("route_id").agg(
        trains=("train_id", "nunique"), trips_min=("n_trips", "min"), trips_median=("n_trips", "median"),
        trips_max=("n_trips", "max"), trav_median=("n_traversals", "median"),
        operating_h_median=("operating_s", lambda x: x.median() / 3600),
        breakdowns=("n_breakdowns", "sum")))
    per_train = td.groupby("train_id")["n_trips"].agg(["min", "max"])
    log(f"- trains whose daily trip count varies across dates: {(per_train['min'] != per_train['max']).sum()} of "
        f"{len(per_train)}; trains-days with incomplete trips: {(td['n_complete_trips'] < td['n_trips']).sum()}")
    log(f"- first event times: {td['first_event_ts'].dt.time.min()} .. {td['first_event_ts'].dt.time.max()}; "
        f"last event times: {td['last_event_ts'].dt.time.min()} .. {td['last_event_ts'].dt.time.max()}")
    within = bd.merge(td[["train_id", "date", "first_event_ts", "last_event_ts"]], on=["train_id", "date"])
    check("breakdowns outside the train's first..last event window",
          int(((within["onset_ts"] < within["first_event_ts"]) | (within["recovery_ts"] > within["last_event_ts"])).sum()))
    # is the daily schedule the same per train every day?
    sched = t[t["dep_event"] == "DEPARTED_ORIGIN"].assign(tod=lambda d: d["dep_ts"] - d["date"])
    sig = sched.groupby(["train_id", "date"])["tod"].agg(lambda x: tuple(x))
    log(f"- distinct daily DEPARTED_ORIGIN timetables per train: median "
        f"{sig.groupby(level=0).nunique().median():.0f}, max {sig.groupby(level=0).nunique().max()}")
    cols = ["train_id", "date", "weekday", "line_id", "route_id", "train_type", "batch_number", "n_trips",
            "n_complete_trips", "n_traversals", "first_event_ts", "last_event_ts", "operating_s",
            "running_s", "dwell_s_total", "turnaround_s_total", "n_breakdowns", "n_bd_segment",
            "n_bd_station", "bd_duration_s"]
    td = td[cols]
    out = td.copy()
    out["date"] = out["date"].dt.strftime("%Y-%m-%d")
    out.to_csv(DERIVED / "train_day.csv", index=False, encoding="utf-8")
    return td


