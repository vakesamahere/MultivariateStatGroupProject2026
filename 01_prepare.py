def load_small() -> dict[str, pd.DataFrame]:
    """Load the small CSVs with every column as text (IDs preserved, blanks -> NA)."""
    d = {}
    for name in ["train_information", "station_information", "breakdown_recovery",
                 "cleaning_records", "temperature", "rainfall"]:
        d[name] = pd.read_csv(DATA / f"{name}.csv", encoding=ENC, dtype=str,
                              keep_default_na=False, na_values=[""])
    return d


def load_ops() -> tuple[pd.DataFrame, int]:
    """Load normal_operations.csv with categorical columns; cache as pickle.

    Returns the frame and the number of timestamp strings that failed to parse.
    """
    cache = DERIVED / "normal_operations.pkl"
    src = DATA / "normal_operations.csv"
    if cache.exists() and cache.stat().st_mtime > src.stat().st_mtime:
        ops = pd.read_pickle(cache)
        return ops, int(ops["timestamp"].isna().sum())
    ops = pd.read_csv(
        src, encoding=ENC, keep_default_na=False, na_values=[""],
        dtype={"timestamp": str, "train_id": "category", "station": "category",
               "event_description": "category"},
    )
    ops["timestamp"] = to_ts(ops["timestamp"])
    ops.to_pickle(cache)
    return ops, int(ops["timestamp"].isna().sum())


