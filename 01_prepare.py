def main() -> None:
    raw = load_small()
    ops, n_bad_ts = load_ops()
    log(f"Loaded inputs in {time.time() - T0:.1f}s (normal_operations: {len(ops):,} rows)")

    br_ts = raw["breakdown_recovery"].assign(timestamp=to_ts(raw["breakdown_recovery"]["timestamp"]))
    cl_ts = raw["cleaning_records"].assign(completed_at=to_ts(raw["cleaning_records"]["completed_at"]))

    overview(raw, ops)
    stations = audit_stations(raw["station_information"])
    trains = audit_trains(raw["train_information"])
    audit_weather(raw["temperature"], raw["rainfall"])
    audit_calendar(ops, br_ts, cl_ts)
    audit_ops_basic(ops, n_bad_ts, trains, stations)
    flush_notes()

    t, trips = build_traversals(ops, trains, stations)
    build_baseline(t)
    flush_notes()

    bd = build_breakdowns(raw["breakdown_recovery"], ops, t, trains, stations)
    flush_notes()

    t = save_traversals(t, bd)
    delay_footprint(t, bd)
    flush_notes()

    td = build_train_day(t, trips, bd, trains)
    flush_notes()

    build_cleaning(raw["cleaning_records"], td, trains)
    write_schemas()
    write_quirks()
    log(f"Total runtime {time.time() - T0:.1f}s")
    flush_notes()


if __name__ == "__main__":
    main()
