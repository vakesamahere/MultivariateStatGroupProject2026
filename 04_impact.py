# --------------------------------------------------------------------------
def prev_in_group(t: pd.DataFrame, station_col: str, ts_col: str) -> np.ndarray:
    """Index of the previous train at the same (line, direction, station), ordered by ts_col."""
    codes = [pd.factorize(t[c])[0] for c in ["line", "dir", station_col]]
    o = np.lexsort((t[ts_col].to_numpy(), codes[2], codes[1], codes[0]))
    same = np.r_[False, (codes[0][o][1:] == codes[0][o][:-1]) & (codes[1][o][1:] == codes[1][o][:-1])
                 & (codes[2][o][1:] == codes[2][o][:-1])]
    out = np.full(len(t), -1)
    k = np.where(same)[0]
    out[o[k]] = o[k - 1]
    return out


def build_leaders(t: pd.DataFrame) -> pd.DataFrame:
    section("1b. Leader-follower links and the blocking (moving-block) rule")
    log("Leader = previous train of the same line and direction at the same station (routes 10/10B merged: "
        "the trunk Longxi Rd S063 .. Jilong Rd S089 is shared). Arrival leader ordered by arrival at the "
        "segment's end station b; departure leader ordered by departure from the start station a.")
    n = len(t)
    nxt = np.arange(n) + 1
    last = t["trip_key"].ne(t["trip_key"].shift(-1)).to_numpy()
    nxt[last] = -1
    t["nxt"] = nxt
    la = prev_in_group(t, "to_station", "arr_ts")
    ld = prev_in_group(t, "from_station", "dep_ts")
    t["lead_arr"], t["lead_dep"] = la, ld
    # R2: follower arrival at b vs leader arrival at its next station c (leader row nxt[la])
    bind_a = np.where(la >= 0, nxt[np.maximum(la, 0)], -1)
    bind_a[la < 0] = -1
    # R1: follower departure from a vs departure from b of the train ahead at b (= the R2 leader's
    # traversal b -> c). Keying on b (not on a) matters at the Line 10 merge into S063, where the
    # train ahead at b may come from the other branch.
    bind_d = bind_a.copy()
    bind_d_a = np.where(ld >= 0, nxt[np.maximum(ld, 0)], -1)  # variant keyed on station a
    bind_d_a[ld < 0] = -1
    t["bind_arr_row"], t["bind_dep_row"] = bind_a, bind_d
    arr = t["arr_ts"].to_numpy()
    dep = t["dep_ts"].to_numpy()
    ga = np.full(n, np.nan)
    ok = bind_a >= 0
    ga[ok] = (arr[ok] - arr[bind_a[ok]]) / np.timedelta64(1, "s")
    gd = np.full(n, np.nan)
    ok = bind_d >= 0
    gd[ok] = (dep[ok] - dep[bind_d[ok]]) / np.timedelta64(1, "s")
    gd_a = np.full(n, np.nan)
    ok = bind_d_a >= 0
    gd_a[ok] = (dep[ok] - dep[bind_d_a[ok]]) / np.timedelta64(1, "s")
    t["gap_arr_s"], t["gap_dep_s"] = ga, gd
    # follower departure while the train ahead is still inside segment b -> c (released before arriving)
    in_seg = np.zeros(n, dtype=bool)
    ok = bind_d >= 0
    in_seg[ok] = (dep[ok] >= dep[bind_d[ok]]) & (dep[ok] <= arr[bind_d[ok]])
    t["dep_while_leader_in_seg"] = in_seg
    # FIFO at stations: the departure leader of the follower's next traversal (from b) must be the
    # continuation of its arrival leader at b, unless the arrival leader terminates at b
    has = (nxt >= 0) & (la >= 0) & (bind_a >= 0)
    fifo_bad = has & (ld[np.maximum(nxt, 0)] != bind_a)
    check("overtaking at a station (arrival order at b != departure order from b)", int(fifo_bad.sum()))
    check("R2 violations: follower arrives at b before leader arrives at next station c", int((ga < 0).sum()))
    check("R1 violations: follower departs a before leader departs next station b", int((gd < 0).sum()))
    log(f"- traversals without an R2 binding leader (first train of the day at b, or b is the leader's "
        f"terminal): {int((bind_a < 0).sum()):,}; without R1 leader: {int((bind_d < 0).sum()):,}")
    xt = (t["x_travel"] > 0) & (t["n_bd_on_segment"] == 0)
    xd = (t["x_dwell"] > 0) & ~t["bd_at_from_station"]
    log(f"- slow traversals without own segment incident: {int(xt.sum())}; R2 gap (follower arr b - leader arr c) "
        f"{q(t.loc[xt, 'gap_arr_s'])} s")
    rel = t.loc[xt, "gap_arr_s"] / t.loc[xt, "base_travel_s"]
    check("slow traversals whose R2 gap exceeds the segment base travel time "
          "(follower is released when the leader reaches c, then needs <= base travel to reach b)",
          int((rel > 1).sum() + t.loc[xt, "gap_arr_s"].isna().sum()))
    log(f"- held dwells without own station incident (incl. late origin departures): {int(xd.sum())}; "
        f"R1 gap (follower dep a - leader dep b) {q(t.loc[xd, 'gap_dep_s'])} s")
    bad_a = int((gd_a[xd.to_numpy()] > DWELL_GAP_TOL_S).sum() + np.isnan(gd_a[xd.to_numpy()]).sum())
    log(f"- variant keyed on station a (train ahead when leaving a): {bad_a} held dwells with gap > "
        f"{DWELL_GAP_TOL_S} s (mostly at the Line 10 merge into S063) -> keying on b is the right rule")
    far = xd & ~(t["gap_dep_s"] <= DWELL_GAP_TOL_S)
    log(f"- held dwells with R1 gap > {DWELL_GAP_TOL_S} s: {int(far.sum())}; of these, departing while the "
        f"train ahead is still held inside segment b -> c (released there, so bound by that train's "
        f"blocked arrival at c): {int((far & t['dep_while_leader_in_seg']).sum())}")
    check("held dwells explained by neither R1 nor the leader-held-in-segment fallback",
          int((far & ~t["dep_while_leader_in_seg"]).sum()))
    flush_notes()
    return t


