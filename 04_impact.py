def load() -> tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    t = pd.read_pickle(DERIVED / "traversals.pkl")
    base = pd.read_csv(DERIVED / "segment_baseline.csv", dtype={"route_id": str, "line_id": str})
    bd = pd.read_csv(DERIVED / "breakdowns.csv", dtype={"line_id": str, "route_id": str, "trip_key": int},
                     parse_dates=["onset_ts", "recovery_ts", "date"])
    st = pd.read_csv(DATA / "station_information.csv", encoding="utf-8-sig", dtype=str)
    st["sequence"] = st["sequence"].astype(int)

    t = t.sort_values(["trip_key", "dep_ts"]).reset_index(drop=True)
    key = base.set_index(["route_id", "segment"])["median_travel_s"]
    idx = pd.MultiIndex.from_arrays([t["route_id"].astype(str), t["segment"].astype(str)])
    t["base_travel_s"] = key.reindex(idx).to_numpy()
    t["line"] = t["line_id"].astype(str)
    t["dir"] = t["direction"].astype(str)
    return t, bd, st


def add_bursts(bd: pd.DataFrame) -> pd.DataFrame:
    """Attach burst membership computed by 02_screening (burst_id = -1 for isolated incidents)."""
    ev = pd.read_csv(SCREEN_EVENTS, parse_dates=["onset"])[["train_id", "onset", "burst_id", "in_burst"]]
    bd = bd.merge(ev, left_on=["train_id", "onset_ts"], right_on=["train_id", "onset"], how="left",
                  validate="one_to_one")
    bd["burst_id"] = bd["burst_id"].fillna(-1).astype(int)
    bd["in_burst"] = bd["in_burst"].fillna(False).astype(bool)
    return bd.drop(columns=["onset"])


def canonical_positions(st: pd.DataFrame) -> dict[str, dict[str, int]]:
    """Position of every station along its line, in stations (route 10/10B aligned on the shared trunk)."""
    out: dict[str, dict[str, int]] = {}
    for line, g in st.groupby("line_id"):
        routes = {r: d.set_index("station_id")["sequence"].astype(int) for r, d in g.groupby("route_id")}
        base = max(routes, key=lambda r: len(routes[r]))
        pos = {k: int(v) for k, v in routes[base].items()}
        for r, s in routes.items():
            if r == base:
                continue
            shared = [k for k in s.index if k in pos]
            off = int(np.median([pos[k] - int(s[k]) for k in shared]))
            for k, v in s.items():
                pos.setdefault(k, int(v) + off)
        out[line] = pos
    return out


