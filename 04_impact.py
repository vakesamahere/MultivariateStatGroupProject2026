def log(msg: str = "") -> None:
    print(msg, flush=True)
    REPORT.append(msg)


def section(title: str) -> None:
    log("")
    log(f"## {title}")
    log(f"_(elapsed {time.time() - T0:.1f}s)_")
    log("")


def paper(msg: str = "") -> None:
    """Paper-ready prose: printed and collected for the top of the notes file."""
    print(msg, flush=True)
    PAPER.append(msg)


def check(label: str, n: int) -> int:
    """Deterministic check: exhaustive count that is expected to be zero."""
    log(f"- [check] {label}: {n}{' **<-- violation**' if n else ''}")
    return n


def table(df: pd.DataFrame) -> None:
    d = df.reset_index() if df.index.name or isinstance(df.index, pd.MultiIndex) else df
    cols = [str(c) for c in d.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in d.itertuples(index=False):
        lines.append("| " + " | ".join(
            (f"{v:.3g}" if isinstance(v, (float, np.floating)) and not float(v).is_integer() else
             (str(int(v)) if isinstance(v, (float, np.floating)) and not pd.isna(v) else str(v)))
            for v in row) + " |")
    log("\n".join(lines))
    log("")


def flush_notes() -> None:
    header = (
        "> Generated by `src/04_impact.py`; re-run to regenerate. Every number below is computed, never "
        "typed in. `[check]` lines in the appendix are exhaustive deterministic checks (expected 0); "
        "everything labelled CI / SE is statistical inference with standard errors clustered by service "
        "date.\n"
    )
    body = "\n".join(PAPER)
    appendix = ("\n---\n\n# Appendix: full computed evidence log\n\n"
                "Everything below is produced by the run and is the evidence for the section above.\n\n"
                + "\n".join(REPORT))
    (NOTES / "04_impact.md").write_text(header + body + appendix + "\n", encoding="utf-8")


def q(s: pd.Series) -> str:
    """Compact distribution string."""
    s = pd.Series(s).dropna()
    if s.empty:
        return "n=0"
    p = s.quantile([0, .25, .5, .75, .9, 1]).round(1).tolist()
    return (f"n={len(s)}, mean {s.mean():.1f}, min {p[0]:g}, p25 {p[1]:g}, median {p[2]:g}, "
            f"p75 {p[3]:g}, p90 {p[4]:g}, max {p[5]:g}")


