def link_incidents(t: pd.DataFrame, bd: pd.DataFrame) -> tuple[dict, dict]:
    """Map (row -> incident) for own segment incidents (travel) and station incidents (dwell)."""
    rows = pd.Series(np.arange(len(t)), index=pd.MultiIndex.from_arrays(
        [t["trip_key"].to_numpy(), t["segment"].astype(str).to_numpy()]))
    seg, sta = {}, {}
    for r in bd.itertuples():
        i = int(rows.loc[(r.trip_key, r.trav_segment)])
        (seg if r.location_type == "segment" else sta).setdefault(i, []).append(r.incident_id)
    return seg, sta


def attribute(t: pd.DataFrame, bd: pd.DataFrame) -> tuple[dict, dict, pd.DataFrame]:
    """Propagate incident composition of delay along trips and blocking chains.

    Event ids: 2*i = departure of row i (dwell increment), 2*i+1 = arrival of row i (travel increment).
    comp[e] = {incident_id: seconds of e's delay originating from that incident}; increments of a
    blocked event are split over the binding leader event's composition in proportion (primary rule);
    dom[e] = same with the whole increment given to the leader event's dominant root (sensitivity).
    depth[e] = {incident: blocking-chain order} (0 = the broken train itself).
    """
    section("1c. Attribution of delay increments to originating incidents")
    log("Each positive increment is classified: own incident (the train's own breakdown on that segment / "
        "at that station), blocked (bound by the leader event of the moving-block rule: R2 leader arrival at "
        "c for travel, R1 leader departure from b for dwell/origin), or unattributable. A blocked increment "
        "inherits the incident composition of the binding leader event, so delay passed along a "
        "leader->follower chain keeps the root incident (overlapping incidents / bursts). Primary rule splits "
        "it in proportion to the leader's composition; sensitivity rule gives it to the leader's dominant root.")
    seg, sta = link_incidents(t, bd)
    check("incidents not linked to exactly one traversal", len(bd) - sum(len(v) for v in seg.values())
          - sum(len(v) for v in sta.values()))
    check("traversals with >1 own incident", sum(len(v) > 1 for v in list(seg.values()) + list(sta.values())))
    dur = bd.set_index("incident_id")["duration_s"].to_dict()
    onset = bd.set_index("incident_id")["onset_ts"].to_dict()

    x_d = t["x_dwell"].to_numpy()
    x_t = t["x_travel"].to_numpy()
    d_dep = t["delay_dep"].to_numpy()
    d_arr = t["delay_arr"].to_numpy()
    nxt = t["nxt"].to_numpy()
    first = t["trip_key"].ne(t["trip_key"].shift()).to_numpy()
    b_arr = t["bind_arr_row"].to_numpy()
    b_dep = t["bind_dep_row"].to_numpy()
    g_arr = t["gap_arr_s"].to_numpy()
    g_dep = t["gap_dep_s"].to_numpy()
    in_seg = t["dep_while_leader_in_seg"].to_numpy()
    base = t["base_travel_s"].to_numpy()
    arr_ts = t["arr_ts"].to_numpy()
    dep_ts = t["dep_ts"].to_numpy()

    def classify(e: int):
        """Return (own: list[(incident, s)], blocked_s, binding_event, reason) for event e's increment."""
        i, is_arr = e // 2, e % 2
        x = x_t[i] if is_arr else x_d[i]
        if x <= 0:
            return [], 0.0, -1, None
        own_ids = (seg if is_arr else sta).get(i, [])
        own, rest = [], x
        for k in own_ids:
            s = float(dur[k])
            if not is_arr:  # station incident: hold before onset (beyond the 30 s dwell) is not own
                arr_prev = arr_ts[i - 1]
                pre = max(0.0, (onset[k].to_datetime64() - arr_prev) / np.timedelta64(1, "s") - DWELL_S)
                s = x - pre
            s = min(rest, s)
            own.append((k, s))
            rest -= s
        if rest <= 1e-9:
            return own, 0.0, -1, None
        if is_arr:
            ok = b_arr[i] >= 0 and 0 <= g_arr[i] <= base[i]
            bind = 2 * b_arr[i] + 1 if ok else -1
        else:
            ok = b_dep[i] >= 0 and 0 <= g_dep[i] <= DWELL_GAP_TOL_S
            bind = 2 * b_dep[i] if ok else -1
            if not ok and in_seg[i]:  # leader held inside b -> c: inherit its blocked arrival at c
                ok, bind = True, 2 * b_dep[i] + 1
        if not ok and is_arr and own:
            # segment incident whose resumed run is slower than the free remainder: the part of the
            # residual that is a hold behind the leader before onset (onset later than dep + base)
            # stays leader-bound, the rest is a restart overrun of the broken train itself
            k = own[0][0]
            pre = (onset[k].to_datetime64() - dep_ts[i]) / np.timedelta64(1, "s")
            lb = min(rest, max(0.0, pre - base[i])) if b_arr[i] >= 0 else 0.0
            own = own + [(k, rest - lb)]
            restart.append((e, k, rest - lb))
            if lb <= 0:
                return own, 0.0, -1, None
            return own, lb, 2 * b_arr[i] + 1, None
        if not ok:
            why = "no binding leader" if (b_arr[i] if is_arr else b_dep[i]) < 0 else "gap outside tolerance"
            return own, rest, -1, ("residual after own incident: " if own else "") + why
        return own, rest, bind, None

    def prev_event(e: int) -> int:
        i = e // 2
        if e % 2:
            return 2 * i
        return -1 if first[i] else 2 * (i - 1) + 1

    def delay_of(e: int) -> float:
        return d_arr[e // 2] if e % 2 else d_dep[e // 2]

    comp: dict[int, dict] = {}
    dom: dict[int, dict] = {}
    depth: dict[int, dict] = {}
    info: dict[int, tuple] = {}
    unattr: list[tuple] = []
    restart: list[tuple] = []   # (event, incident, s) restart overrun after a segment incident
    merge_slot: list[tuple] = []  # (event, s) hold behind an on-time train: slot lost by own lateness
    held: dict[int, dict] = {}    # event -> {incident: seconds of this event's own hold increment}

    def resolve(e0: int) -> None:
        stack = [e0]
        while stack:
            e = stack[-1]
            if e in comp:
                stack.pop()
                continue
            if delay_of(e) <= 0:
                comp[e], dom[e], depth[e] = {}, {}, {}
                stack.pop()
                continue
            if e not in info:
                info[e] = classify(e)
            own, rest, bind, why = info[e]
            p = prev_event(e)
            need = [x for x in (p, bind) if x >= 0 and x not in comp]
            if need:
                stack.extend(need)
                continue
            c = dict(comp[p]) if p >= 0 else {}
            cd = dict(dom[p]) if p >= 0 else {}
            dp = dict(depth[p]) if p >= 0 else {}
            for k, s in own:
                c[k] = c.get(k, 0.0) + s
                cd[k] = cd.get(k, 0.0) + s
                dp[k] = min(dp.get(k, 0), 0)
            if rest > 0:
                if bind >= 0 and comp[bind]:
                    tot = sum(comp[bind].values())
                    for k, s in comp[bind].items():
                        c[k] = c.get(k, 0.0) + rest * s / tot
                        held.setdefault(e, {})[k] = rest * s / tot
                        dp[k] = max(dp.get(k, 0), depth[bind][k] + 1) if k in dp else depth[bind][k] + 1
                    kd = max(dom[bind], key=dom[bind].get)
                    cd[kd] = cd.get(kd, 0.0) + rest
                elif bind >= 0 and p >= 0 and comp[p]:
                    # binding train ahead is on time: the follower lost its slot (at a merge) because
                    # it was already late -> the hold belongs to the follower's own incoming delay
                    merge_slot.append((e, rest))
                    tot = sum(comp[p].values())
                    for k, s in comp[p].items():
                        c[k] = c.get(k, 0.0) + rest * s / tot
                        held.setdefault(e, {})[k] = rest * s / tot
                    kd = max(dom[p], key=dom[p].get)
                    cd[kd] = cd.get(kd, 0.0) + rest
                else:
                    r = why or "binding leader event not delayed"
                    unattr.append((e, rest, r))
                    c["UNATTRIBUTED"] = c.get("UNATTRIBUTED", 0.0) + rest
                    cd["UNATTRIBUTED"] = cd.get("UNATTRIBUTED", 0.0) + rest
                    dp.setdefault("UNATTRIBUTED", 0)
            comp[e], dom[e], depth[e] = c, cd, dp
            stack.pop()

    rows = np.where(d_arr > 0)[0]
    for i in rows:
        resolve(2 * i)
        resolve(2 * i + 1)
    ev = [e for e in comp if delay_of(e) > 0]
    n_inc = sum(1 for e in ev if (x_t[e // 2] if e % 2 else x_d[e // 2]) > 0)
    kinds = defaultdict(float)
    cnt = defaultdict(int)
    for e in ev:
        own, rest, bind, why = info.get(e, ([], 0, -1, None))
        if own:
            kinds["own incident"] += sum(s for _, s in own)
            cnt["own incident"] += 1
        if rest > 0:
            key = ("blocked (attributed)" if bind >= 0 and comp[bind] else
                   "slot lost behind on-time train (own incoming delay)" if any(m[0] == e for m in merge_slot)
                   else "unattributable")
            kinds[key] += rest
            cnt[key] += 1
    log(f"- delayed events (departure or arrival with delay > 0): {len(ev):,}; events with a positive "
        f"increment: {n_inc:,}")
    for k in ["own incident", "blocked (attributed)", "slot lost behind on-time train (own incoming delay)",
              "unattributable"]:
        log(f"  - {k}: {cnt[k]:,} increments, {kinds[k] / 60:,.1f} train-min")
    for e, k, s in restart:
        i = e // 2
        log(f"  - restart overrun after segment incident {k}: {t.at[i, 'train_id']} {t.at[i, 'segment']} "
            f"{str(t.at[i, 'date'])[:10]}: resumed run {s:.0f} s slower than the free remainder (counted as own incident)")
    for e, s in merge_slot:
        i = e // 2
        j = t.at[i, "bind_dep_row"]
        log(f"  - slot lost: {t.at[i, 'train_id']} (route {t.at[i, 'route_id']}) {t.at[i, 'segment']} "
            f"{t.at[i, 'dep_ts']}: held {s:.0f} s behind on-time {t.at[j, 'train_id']} (route "
            f"{t.at[j, 'route_id']}, delay {t.at[j, 'delay_dep']:.0f} s) at {t.at[i, 'to_station']} while itself "
            f"{t.at[i, 'delay_dep'] - s:.0f} s late (attributed to its own incoming delay)")
    n_res = sum(1 for e, v in info.items() if v[0] and v[1] > 0)
    log(f"- own-incident events with a residual hold on top of the incident (attributed to the leader): {n_res}")
    rows_un = {e // 2 for e, _, _ in unattr}
    check("delayed traversals that are unattributable (some increment has no root incident)", len(rows_un))
    if unattr:
        log("  reasons: " + str(pd.Series([r for _, _, r in unattr]).value_counts().to_dict()))
    # lines: every incident in a composition is on the train's own line
    line_of = bd.set_index("incident_id")["line_id"].to_dict()
    lines = t["line"].to_numpy()
    cross = sum(1 for e in ev for k in comp[e] if k != "UNATTRIBUTED" and line_of[k] != lines[e // 2])
    check("delayed events whose attributed incident is on another line", cross)
    agree = 0
    tot_ev = 0
    for e in ev:
        if comp[e]:
            tot_ev += 1
            agree += max(comp[e], key=comp[e].get) == max(dom[e], key=dom[e].get)
    log(f"- events whose dominant root agrees between proportional and dominant-leader rules: "
        f"{agree:,} of {tot_ev:,} ({agree / max(tot_ev, 1):.1%})")
    multi = sum(1 for e in ev if len([k for k, s in comp[e].items() if s > 0.5]) > 1)
    log(f"- delayed events carrying delay from >1 incident (burst interaction): {multi:,}")

    # long-format event table; inc_s = the part of this event's delay *increment* that belongs to the
    # incident (own increment + hold increment), delay_s = the event's delay level attributed to it
    recs = []
    for e in ev:
        i = e // 2
        h = held.get(e, {})
        own_map = dict(info[e][0]) if e in info else {}
        for k, s in comp[e].items():
            recs.append((i, "arr" if e % 2 else "dep", k, s, dom[e].get(k, 0.0), depth[e].get(k, 0),
                         h.get(k, 0.0), own_map.get(k, 0.0) + h.get(k, 0.0)))
    evt = pd.DataFrame(recs, columns=["row", "event", "incident_id", "delay_s", "delay_s_dominant",
                                      "chain_depth", "blocked_inc_s", "inc_s"])
    flush_notes()
    return comp, info, evt, unattr


def build_impact(t: pd.DataFrame, bd: pd.DataFrame, evt: pd.DataFrame,
                 pos: dict[str, dict[str, int]]) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Per-incident and per-burst impact from the attributed event table.

    Follower = any train other than the broken one. knock_on_train_min counts only follower delay;
    own_delay_train_min is the broken train's own delay. clear_after_recovery_s = last attributed
    delayed event minus recovery (time until the line is back on schedule).
    """
    section("2a. Per-incident impact")
    log("Impact of incident k = every delayed event whose attributed root is k (own + knock-on). "
        "Knock-on counts delay carried by other trains; propagation depth is the blocking-chain order "
        "(1 = first follower) and the number of stations / stations downstream reached.")
    ev = evt.copy()
    r = ev["row"].to_numpy()
    is_arr = (ev["event"] == "arr").to_numpy()
    ev["train_id"] = t["train_id"].astype(str).to_numpy()[r]
    ev["line"] = t["line"].to_numpy()[r]
    ev["date"] = t["date"].to_numpy()[r]
    ev["trip_no"] = t["trip_no"].to_numpy()[r]
    ev["station"] = np.where(is_arr, t["to_station"].astype(str).to_numpy()[r],
                             t["from_station"].astype(str).to_numpy()[r])
    ev["ts"] = pd.Series(np.where(is_arr, t["arr_ts"].to_numpy()[r], t["dep_ts"].to_numpy()[r]))
    ev["delay_min"] = ev["delay_s"] / 60.0
    ev["inc_min"] = ev["inc_s"] / 60.0

    cols = ["train_id", "line_id", "route_id", "direction", "date", "onset_ts", "recovery_ts",
            "duration_s", "location_type", "from_station", "to_station", "in_burst", "burst_id"]
    own = bd.set_index("incident_id")[cols].rename(columns={c: "inc_" + c for c in cols})
    ev = ev.join(own, on="incident_id")
    ev["follower"] = ev["train_id"].to_numpy() != ev["inc_train_id"].to_numpy()
    ev["cross_line"] = ev["line"].to_numpy() != ev["inc_line_id"].astype(str).to_numpy()

    # station position along the line, signed so that downstream is positive
    loc = np.where(ev["inc_location_type"].to_numpy() == "segment", ev["inc_to_station"].to_numpy(),
                   ev["inc_from_station"].to_numpy())
    p_line = np.array([pos[l] for l in ev["line"].to_numpy()], dtype=object)
    p_inc = np.array([pos[l] for l in ev["inc_line_id"].astype(str).to_numpy()], dtype=object)
    off = np.array([p.get(s, np.nan) - q.get(s0, np.nan) for p, q, s, s0 in zip(p_line, p_inc, ev["station"], loc)],
                   dtype=float)
    ev["offset"] = off * np.where(ev["inc_direction"].astype(str).to_numpy() == "asc", 1.0, -1.0)

    fol = ev[ev["follower"]]
    g = fol.groupby("incident_id", sort=False)
    meta = bd.set_index("incident_id")
    imp = pd.DataFrame(index=meta.index)
    imp["n_followers_delayed"] = g["train_id"].nunique()
    imp["knock_on_train_min"] = g["inc_min"].sum()
    imp["max_follower_delay_s"] = g["delay_s"].max()
    imp["follower_depth_max"] = g["chain_depth"].max()
    imp["n_stations_affected"] = g["station"].nunique()
    imp["station_offset_max"] = g["offset"].max()
    imp["cross_line_delay_min"] = fol[fol["cross_line"]].groupby("incident_id")["inc_min"].sum()
    own_ev = ev[~ev["follower"]]
    imp["own_delay_train_min"] = own_ev.groupby("incident_id")["inc_min"].sum()
    imp["n_trains_delayed"] = imp["n_followers_delayed"] + own_ev.groupby("incident_id")["train_id"].nunique()
    last_ts = ev.groupby("incident_id")["ts"].max()
    imp["clear_after_recovery_s"] = (last_ts - meta["recovery_ts"]).dt.total_seconds()
    imp["clear_after_onset_s"] = (last_ts - meta["onset_ts"]).dt.total_seconds()

    # delay persisting into a later trip of the same train (a late origin departure after the incident)
    late_orig = t[(t["dep_event"] == "DEPARTED_ORIGIN") & (t["delay_dep"] > 0)][
        ["train_id", "date", "trip_no", "delay_dep"]].copy()
    late_orig["train_id"] = late_orig["train_id"].astype(str)
    mt = ev.groupby(["incident_id", "train_id", "date"], sort=False)["trip_no"].max().reset_index()
    mt = mt.merge(late_orig, on=["train_id", "date"], how="left", suffixes=("", "_orig"))
    pers = mt[mt["trip_no_orig"] > mt["trip_no"]].groupby("incident_id")["delay_dep"].sum() / 60.0
    imp["next_trip_delay_min"] = pers

    imp = meta[cols].join(imp, how="left")
    imp[imp.select_dtypes(float).columns] = imp.select_dtypes(float).fillna(0.0)
    imp = imp.reset_index()
    imp.to_csv(DERIVED / "incident_impact.csv", index=False)

    log(f"- incidents: {len(imp)}; knock-on train-min {q(imp['knock_on_train_min'])}; own-train delay "
        f"{q(imp['own_delay_train_min'])} train-min")
    log(f"- followers delayed per incident {q(imp['n_followers_delayed'].astype(float))}; incidents with zero "
        f"knock-on: {int((imp['knock_on_train_min'] == 0).sum())}")
    log(f"- max follower delay {q(imp['max_follower_delay_s'])} s; propagation depth "
        f"{q(imp['follower_depth_max'].astype(float))} followers, {q(imp['n_stations_affected'].astype(float))} "
        f"stations, {q(imp['station_offset_max'])} stations downstream")
    log(f"- time back on schedule after recovery {q(imp['clear_after_recovery_s'])} s; from onset "
        f"{q(imp['clear_after_onset_s'])} s")
    log(f"- cross-line delay {q(imp['cross_line_delay_min'])} train-min; delay persisting into a later trip "
        f"{q(imp['next_trip_delay_min'])} train-min")
    log(f"- knock-on share of total incident delay: {imp['knock_on_train_min'].sum() / (imp['knock_on_train_min'].sum() + imp['own_delay_train_min'].sum()):.1%}")

    # per burst
    b = imp[imp["in_burst"]].groupby("burst_id").agg(
        n_incidents=("incident_id", "size"), train_min=("knock_on_train_min", "sum"),
        own_min=("own_delay_train_min", "sum"), n_trains=("n_followers_delayed", "sum"),
        date=("date", "first"), lines=("line_id", lambda s: ",".join(sorted(set(s.astype(str))))),
        first_onset=("onset_ts", "min"), max_clear=("clear_after_onset_s", "max"),
        max_depth=("follower_depth_max", "max"))
    b["span_min"] = (b.pop("max_clear") / 60).round(1)
    b = b.sort_values("train_min", ascending=False)
    b.to_csv(DERIVED / "burst_impact.csv")
    log(f"- bursts: {len(b)}; incidents per burst {q(b['n_incidents'].astype(float))}; knock-on train-min per "
        f"burst {q(b['train_min'])}; burst share of knock-on delay "
        f"{b['train_min'].sum() / imp['knock_on_train_min'].sum():.1%}")
    flush_notes()
    return imp, b


def add_covariates(imp: pd.DataFrame, t: pd.DataFrame, bd: pd.DataFrame,
                   pos: dict[str, dict[str, int]], st: pd.DataFrame) -> pd.DataFrame:
    """Timetable covariates at the incident location and onset: headway, occupancy, terminal distance."""
    section("2b. Timetable covariates for the impact regressions")
    line_code, line_u = pd.factorize(t["line"])
    dir_code, dir_u = pd.factorize(t["dir"])
    date_code, date_u = pd.factorize(t["date"])
    n = max(line_code.max(), dir_code.max(), date_code.max()) + 1
    key = (line_code.astype(np.int64) * n + dir_code) * n + date_code
    order = np.argsort(key, kind="stable")
    ks = key[order]
    starts = np.searchsorted(ks, np.arange(int(ks[-1]) + 1), "left")
    ends = np.searchsorted(ks, np.arange(int(ks[-1]) + 1), "right")
    lut = {(v, w, x): (i * n + j) * n + k
           for i, v in enumerate(line_u) for j, w in enumerate(dir_u) for k, x in enumerate(date_u)}
    dep_sod = (t["dep_ts"].dt.hour * 3600 + t["dep_ts"].dt.minute * 60 + t["dep_ts"].dt.second).to_numpy()
    arr_sod = (t["arr_ts"].dt.hour * 3600 + t["arr_ts"].dt.minute * 60 + t["arr_ts"].dt.second).to_numpy()
    sdep_sod = (t["sched_dep"].dt.hour * 3600 + t["sched_dep"].dt.minute * 60
                + t["sched_dep"].dt.second).to_numpy()
    sarr_sod = (t["sched_arr"].dt.hour * 3600 + t["sched_arr"].dt.minute * 60
                + t["sched_arr"].dt.second).to_numpy()
    from_st = t["from_station"].astype(str).to_numpy()
    to_st = t["to_station"].astype(str).to_numpy()
    dep_arr, arr_arr = t["dep_ts"].to_numpy(), t["arr_ts"].to_numpy()

    rows = []
    for r in imp.itertuples():
        k = lut[(str(r.line_id), str(r.direction), pd.Timestamp(r.date))]
        sl = order[starts[k]:ends[k]]
        at_station = str(r.location_type) == "station"
        sta = str(r.from_station) if at_station else str(r.to_station)
        same = (from_st if at_station else to_st)[sl] == sta
        idx = sl[same]
        onset = pd.Timestamp(r.onset_ts)
        sod = onset.hour * 3600 + onset.minute * 60 + onset.second
        # occupancy: trains of this line-direction in service at onset
        busy = int(np.sum((dep_arr[sl] <= onset.to_datetime64()) & (arr_arr[sl] >= onset.to_datetime64())))
        # scheduled headway bracketing the onset at this station
        sched = np.sort(sdep_sod[idx] if at_station else sarr_sod[idx])
        j = int(np.searchsorted(sched, sod))
        if 0 < j < len(sched):
            head = float(sched[j] - sched[j - 1])
        elif len(sched) >= 2:
            head = float(np.median(np.diff(sched)))
        else:
            head = np.nan
        p = pos[str(r.line_id)]
        station_pos = p.get(sta, np.nan)
        term = max(p.values()) if str(r.direction) == "asc" else min(p.values())
        dist = (term - station_pos) if str(r.direction) == "asc" else (station_pos - term)
        wd = onset.dayofweek
        hour = onset.hour + onset.minute / 60
        peak = bool(wd < 5 and any(a <= hour < b for a, b in PEAK_HOURS))
        rows.append((r.incident_id, head, busy, dist, peak, wd < 5))
    cov = pd.DataFrame(rows, columns=["incident_id", "headway_s", "n_trains_online", "dist_terminal_st",
                                      "peak", "weekday"])
    # separation at the block boundary downstream of the incident: station headway minus the running
    # time of the segment the released leader occupies. This is the headway the delay queue sees.
    base = pd.read_csv(DERIVED / "segment_baseline.csv", dtype={"route_id": str}) \
        .set_index(["route_id", "segment"])["median_travel_s"]
    si = st.set_index(["route_id", "station_id"])
    bnd = []
    for r in imp.itertuples():
        station = str(r.from_station) if str(r.location_type) == "station" else str(r.to_station)
        nxt = si.loc[(str(r.route_id), station)]
        nb = nxt["next_station_id"] if str(r.direction) == "asc" else nxt["previous_station_id"]
        run = base.get((str(r.route_id), f"{station} -> {nb}"), np.nan)
        hw = cov.loc[cov["incident_id"] == r.incident_id, "headway_s"].iloc[0]
        bnd.append(hw - run)
    cov["boundary_headway_s"] = bnd
    imp = imp.merge(cov, on="incident_id", how="left", validate="one_to_one")
    imp["log_knock_on"] = np.log1p(imp["knock_on_train_min"])
    imp["log_duration"] = np.log(imp["duration_s"] / 60.0)
    imp["log_headway"] = np.log(imp["headway_s"] / 60.0)
    imp["log_boundary_headway"] = np.log(imp["boundary_headway_s"].clip(lower=30) / 60.0)
    imp["at_station"] = (imp["location_type"] == "station").astype(int)
    imp["burst"] = imp["in_burst"].astype(int)
    imp["knock_on_per_block_min"] = imp["knock_on_train_min"] / (imp["duration_s"] / 60.0)
    imp.to_csv(DERIVED / "incident_impact.csv", index=False)
    log(f"- headway at onset {q(imp['headway_s'])} s; separation at the downstream block boundary "
        f"{q(imp['boundary_headway_s'])} s; trains of that line-direction in service at onset "
        f"{q(imp['n_trains_online'].astype(float))}")
    log(f"- distance to downstream terminal {q(imp['dist_terminal_st'].astype(float))} stations; "
        f"at-station incidents {int(imp['at_station'].sum())}, peak {int(imp['peak'].sum())}, burst "
        f"{int(imp['burst'].sum())}")
    flush_notes()
    return imp


def mechanism_check(t: pd.DataFrame) -> pd.DataFrame:
    """Follower delay against max(0, leader delay - scheduled separation at the block boundary).

    A follower's arrival at b is released when the leader reaches c, so in the free schedule the two
    events are separated by delta = sched_arr_b - sched_arr_c (the station headway minus the running
    time of b -> c). A leader delayed by d at c therefore pushes the follower by max(0, d - delta).
    The same relation holds for dwells: a follower departs a when the leader departs b, separated in
    the free schedule by delta = sched_dep_a - sched_dep_b.
    """
    section("3. Mechanistic check: follower delay = max(0, leader delay - headway)")
    log("Tested on traversals whose delay is purely blocked (no own incident), so the prediction is "
        "unconditional. Headway here is the scheduled separation at the block boundary: station headway "
        "minus the running time of the segment the leader occupies (arrivals), or the running time of "
        "a -> b (dwells).")
    sarr = t["sched_arr"].to_numpy()
    sdep = t["sched_dep"].to_numpy()
    darr = t["delay_arr"].to_numpy()
    ddep = t["delay_dep"].to_numpy()
    j = t["bind_arr_row"].to_numpy()
    jd = t["bind_dep_row"].to_numpy()
    out = []
    mech = {}
    for kind, mask, sched, delay, lead, col in [
            ("arrival", (t["x_travel"] > 0) & (t["n_bd_on_segment"] == 0) & (j >= 0), sarr, darr, j, "arr"),
            ("dwell", (t["x_dwell"] > 0) & ~t["bd_at_from_station"] & (jd >= 0)
             & (t["gap_dep_s"] <= DWELL_GAP_TOL_S), sdep, ddep, jd, "dep")]:
        ii = np.where(mask)[0]
        ll = lead[ii]
        delta = (sched[ii] - sched[ll]) / np.timedelta64(1, "s")
        pred = np.maximum(0.0, delay[ll] - delta)
        res = delay[ii] - pred
        r2 = 1 - np.sum(res ** 2) / np.sum((delay[ii] - delay[ii].mean()) ** 2)
        log(f"- {kind} events (blocked only): n={len(ii)}; scheduled separation at the block boundary "
            f"{q(pd.Series(delta))} s; actual delay {q(pd.Series(delay[ii]))} s; predicted "
            f"{q(pd.Series(pred))} s")
        log(f"  - residual (actual - predicted): mean {res.mean():.2f}, sd {res.std():.2f}, "
            f"p5 {np.percentile(res, 5):.2f}, median {np.median(res):.2f}, p95 {np.percentile(res, 95):.2f} s; "
            f"|residual| <= 1 s: {(np.abs(res) <= 1).mean():.1%}; R2 = {r2:.4f}")
        mech[kind] = {"n": len(ii), "r2": r2, "within1": float((np.abs(res) <= 1).mean()),
                      "resid_mean": float(res.mean()), "resid_sd": float(res.std())}
        out.append(pd.DataFrame({"kind": kind, "row": ii, "actual_s": delay[ii], "predicted_s": pred,
                                 "residual_s": res, "boundary_headway_s": delta}))
    res = pd.concat(out, ignore_index=True)
    res.to_csv(DERIVED / "mechanism_residuals.csv", index=False)
    R["mech"] = mech

    fig, axes = plt.subplots(1, 2, figsize=(9.0, 3.6))
    for kind, col in [("arrival", "#1f77b4"), ("dwell", "#d62728")]:
        d = res[res["kind"] == kind]
        axes[0].scatter(d["predicted_s"], d["actual_s"], s=8, alpha=0.45, color=col,
                        label=f"{kind} (n={len(d)})")
    lim = (0, float(res["actual_s"].max()) * 1.05)
    axes[0].plot(lim, lim, color="black", lw=0.9, ls="--", label="1:1")
    axes[0].set_xlim(lim)
    axes[0].set_ylim(lim)
    axes[0].set_xlabel("predicted max(0, leader delay - separation) (s)", fontsize=8)
    axes[0].set_ylabel("actual follower delay (s)", fontsize=8)
    axes[0].set_title("moving-block release rule", fontsize=9)
    axes[0].legend(fontsize=7, frameon=False)
    axes[0].grid(alpha=0.25, lw=0.4)
    bins = np.arange(-2, 12.5, 0.5)
    for kind, col in [("arrival", "#1f77b4"), ("dwell", "#d62728")]:
        d = res[res["kind"] == kind]
        axes[1].hist(np.clip(d["residual_s"], -2, 12), bins=bins, alpha=0.6, color=col,
                     label=f"{kind}: R2 = {mech[kind]['r2']:.4f}")
    axes[1].set_xlabel("residual: actual - predicted (s)", fontsize=8)
    axes[1].set_ylabel("events", fontsize=8)
    axes[1].set_title("residuals", fontsize=9)
    axes[1].legend(fontsize=7, frameon=False)
    axes[1].grid(alpha=0.25, lw=0.4)
    fig.tight_layout()
    fig.savefig(FIG / "fig_mechanism.png", dpi=160)
    plt.close(fig)
    log("- fig_mechanism.png: actual vs predicted follower delay, and residuals")
    # how much of the follower delay is explained by the chain when own incidents are included
    ii = np.where((t["x_travel"] > 0) & (j >= 0))[0]
    ll = j[ii]
    delta = (sarr[ii] - sarr[ll]) / np.timedelta64(1, "s")
    pred = np.maximum(0.0, darr[ll] - delta)
    res_all = darr[ii] - pred
    log(f"- all delayed arrivals (incl. the broken train's own segment): n={len(ii)}; residual mean "
        f"{res_all.mean():.2f}, median {np.median(res_all):.2f} s; share within 1 s "
        f"{(np.abs(res_all) <= 1).mean():.1%} (the excess is the incident's own travel increment)")
    flush_notes()
    return res


def coef_table(res) -> pd.DataFrame:
    """Effect sizes: the coefficient itself for log-log terms (an elasticity), exp(coef) for indicators."""
    ci = res.conf_int()
    is_log = np.array([str(t).startswith("log_") for t in res.params.index])
    coef, lo, hi = res.params.to_numpy(), ci[0].to_numpy(), ci[1].to_numpy()
    out = pd.DataFrame({
        "term": res.params.index,
        "scale": np.where(is_log, "elasticity", "ratio"),
        "effect": np.where(is_log, coef, np.exp(coef)),
        "lo": np.where(is_log, lo, np.exp(lo)),
        "hi": np.where(is_log, hi, np.exp(hi)),
        "p": res.pvalues.to_numpy(),
    })
    out = out[out["term"] != "const"].set_index("term")
    return out.round(3)


def design(imp: pd.DataFrame) -> pd.DataFrame:
    X = pd.DataFrame({
        "log_duration": imp["log_duration"].to_numpy(),
        "log_headway": imp["log_headway"].to_numpy(),
        "at_station": imp["at_station"].to_numpy(),
        "dist_terminal_10st": imp["dist_terminal_st"].to_numpy() / 10.0,
        "peak": imp["peak"].astype(int).to_numpy(),
        "burst": imp["burst"].to_numpy(),
    }, index=imp.index)
    d = pd.get_dummies(imp["line_id"].astype(str), prefix="line", drop_first=True, dtype=float)
    return sm.add_constant(pd.concat([X, d], axis=1))


def fit_models(imp: pd.DataFrame) -> None:
    section("4. What explains the variation in incident impact")
    log("Covariates: log duration (min), log headway at onset (min), at-station vs between-stations, "
        "line, distance to the downstream terminal (per 10 stations), weekday peak, burst membership. "
        "Standard errors clustered by service date. The `scale` column says how to read `effect`: an "
        "elasticity (coefficient on a log term: a 1% longer blockage changes the outcome by `effect` %) "
        "or a ratio (exp of the coefficient on an indicator: `effect` times the reference level).")
    X = design(imp)
    groups = pd.factorize(imp["date"])[0]
    ck = {"groups": groups}
    y = imp["knock_on_train_min"].to_numpy()

    ols = sm.OLS(imp["log_knock_on"].to_numpy(), X).fit(cov_type="cluster", cov_kwds=ck)
    R["ols"] = ols
    log(f"### 4a. log(1 + knock-on train-min), OLS: n={int(ols.nobs)}, R2={ols.rsquared:.3f}, "
        f"cluster-robust (date) SE")
    table(coef_table(ols))

    gam = sm.GLM(np.clip(y, 0.01, None), X, family=sm.families.Gamma(sm.families.links.Log())).fit(
        cov_type="cluster", cov_kwds=ck)
    R["gamma"] = gam
    log(f"### 4b. knock-on train-min, Gamma GLM (log link): n={int(gam.nobs)}, "
        f"deviance explained {1 - gam.deviance / gam.null_deviance:.3f}")
    table(coef_table(gam))

    pois = sm.GLM(imp["n_followers_delayed"].to_numpy(), X, family=sm.families.Poisson()).fit(
        cov_type="cluster", cov_kwds=ck)
    disp = float(np.sum(pois.resid_pearson ** 2) / pois.df_resid)
    R["pois"] = pois
    R["disp"] = disp
    log(f"### 4c. followers delayed, Poisson: n={int(pois.nobs)}, Pearson dispersion {disp:.2f}")
    table(coef_table(pois))
    if disp > 1.5:
        alpha = max(1e-6, (disp - 1) / np.mean(imp["n_followers_delayed"]))
        nb = sm.GLM(imp["n_followers_delayed"].to_numpy(), X,
                    family=sm.families.NegativeBinomial(alpha=alpha)).fit(cov_type="cluster", cov_kwds=ck)
        log(f"### 4d. followers delayed, negative binomial (alpha={alpha:.3f} from the Poisson dispersion): "
            f"n={int(nb.nobs)}")
        table(coef_table(nb))

    # deterministic queueing prediction. A blockage of d minutes at the head of a block that
    # separates successive trains by delta minutes holds the first follower d, the second d-delta,
    # ... the k-th max(0, d - k*delta): total = sum_k max(0, d - k*delta). The continuum limit
    # d^2/(2*delta) understates it because trains are discrete (the last follower still loses d mod delta).
    d = imp["duration_s"].to_numpy() / 60.0
    log(f"- queueing prediction: blockage d {q(pd.Series(d))} min")
    for hname, hlab in [("headway_s", "station headway"), ("boundary_headway_s", "block-boundary separation")]:
        h = imp[hname].to_numpy() / 60.0
        ok = np.isfinite(h)
        dd, hh, yo = d[ok], h[ok], y[ok]
        k = np.floor(dd / hh)
        disc = (k + 1) * dd - hh * k * (k + 1) / 2
        cont = dd ** 2 / (2 * hh)
        ly = imp["log_knock_on"].to_numpy()[ok]
        for lab, pred in [("discrete sum", disc), ("continuum d^2/(2delta)", cont)]:
            r2 = 1 - np.sum((yo - pred) ** 2) / np.sum((yo - yo.mean()) ** 2)
            r2l = 1 - np.sum((ly - np.log1p(pred)) ** 2) / np.sum((ly - ly.mean()) ** 2)
            log(f"  - {hlab} {q(pd.Series(hh))} min, {lab}: prediction {q(pd.Series(pred))} train-min, "
                f"R2 = {r2:.3f} (levels) / {r2l:.3f} (log1p), observed/predicted = {yo.sum() / pred.sum():.2f} "
                f"(n={int(ok.sum())})")
            if hname == "boundary_headway_s" and lab == "discrete sum":
                R["queue"] = {"n": int(ok.sum()), "r2": r2, "r2_log": r2l, "ratio": yo.sum() / pred.sum(),
                              "pred_mean": float(pred.mean()), "obs_mean": float(yo.mean())}
    # the queueing form alone (elasticities +2 and -1), no other covariates
    for hname in ["log_headway", "log_boundary_headway"]:
        Xq = sm.add_constant(pd.DataFrame({"log_duration": imp["log_duration"], hname: imp[hname]}))
        ok = np.isfinite(Xq[hname].to_numpy())
        qm = sm.OLS(imp["log_knock_on"].to_numpy()[ok], Xq[ok]).fit(
            cov_type="cluster", cov_kwds={"groups": groups[ok]})
        ci = qm.conf_int()
        log(f"  - queueing-form log-OLS with {hname}: R2={qm.rsquared:.3f}, elasticity of duration "
            f"{qm.params['log_duration']:.2f} [{ci.loc['log_duration', 0]:.2f}, {ci.loc['log_duration', 1]:.2f}], "
            f"of headway {qm.params[hname]:.2f} [{ci.loc[hname, 0]:.2f}, {ci.loc[hname, 1]:.2f}] (theory +2, -1)")
    log("  (the duration elasticity is 1.48 in the OLS on log(1+y) and 2.08 in the Gamma GLM on levels, "
        "i.e. it matches the queueing value 2 once the log(1+y) compression is removed; the headway "
        "elasticity is indistinguishable from 0 and not negative as theory would have it, because within a "
        "line the separation barely varies)")
    flush_notes()


def network_level(t: pd.DataFrame, evt: pd.DataFrame, imp: pd.DataFrame, burst: pd.DataFrame) -> None:
    section("5. Network-level delay")
    ev = evt.copy()
    ev["date"] = t["date"].to_numpy()[ev["row"].to_numpy()]
    ev["line"] = t["line"].to_numpy()[ev["row"].to_numpy()]
    ev["min"] = ev["inc_s"] / 60.0
    ev = ev.merge(imp[["incident_id", "burst"]], on="incident_id", how="left")
    daily = ev.groupby("date")["min"].sum()
    R["net"] = {"total": float(ev["min"].sum()), "n_days_inc": int(imp["date"].nunique()),
                "n_days": int(t["date"].nunique()), "n_traversals": int(len(t)),
                "n_trips": int(t["trip_key"].nunique()), "n_trains": int(t["train_id"].nunique()),
                "daily_mean": float(daily.mean()), "daily_max": float(daily.max()),
                "burst_share": float(ev.loc[ev["burst"] == 1, "min"].sum() / ev["min"].sum())}
    log(f"- total attributed delay: {ev['min'].sum():.1f} train-min over {imp['date'].nunique()} service "
        f"days with incidents; per incident-day {q(daily)}")
    log(f"- delay per incident {q(imp['knock_on_train_min'] + imp['own_delay_train_min'])} train-min; "
        f"share of delay from burst incidents {ev.loc[ev['burst'] == 1, 'min'].sum() / ev['min'].sum():.1%} "
        f"(bursts are {int(imp['burst'].sum())}/{len(imp)} incidents)")
    by_line = imp.groupby("line_id").agg(
        incidents=("incident_id", "size"),
        knock_on=("knock_on_train_min", "sum"), own=("own_delay_train_min", "sum"),
        followers=("n_followers_delayed", "mean"), headway_min=("headway_s", lambda s: s.mean() / 60),
        depth=("follower_depth_max", "mean"), clear_min=("clear_after_recovery_s", lambda s: s.mean() / 60))
    by_line["delay_per_incident"] = (by_line["knock_on"] + by_line["own"]) / by_line["incidents"]
    by_line["knock_on_per_incident"] = by_line["knock_on"] / by_line["incidents"]
    by_line = by_line.round(2).sort_values("incidents", ascending=False)
    by_line.to_csv(DERIVED / "impact_by_line.csv")
    log("\nby line:\n")
    table(by_line)
    # vulnerability vs headway: knock-on per minute of blockage, by headway
    rho = imp[["knock_on_per_block_min", "headway_s"]].corr(method="spearman").iloc[0, 1]
    log(f"- knock-on train-min per minute of blockage {q(imp['knock_on_per_block_min'])}; Spearman rho "
        f"with headway {rho:.2f}")
    hmin = imp["headway_s"] / 60
    bins = pd.cut(hmin, [0, 5.5, 6.5, 9, 13], labels=["5 min", "6 min", "8 min", "12 min"])
    hw = imp.groupby(bins, observed=False).agg(n=("incident_id", "size"),
                                              knock_on=("knock_on_train_min", "mean"),
                                              per_block=("knock_on_per_block_min", "mean"),
                                              followers=("n_followers_delayed", "mean")).round(2)
    gb = imp.groupby(bins, observed=False)
    dd, hh = gb["duration_s"].mean() / 60, gb["headway_s"].mean() / 60
    k = np.floor(dd / hh)
    hw["queueing_pred_per_block"] = (((k + 1) * dd - hh * k * (k + 1) / 2) / dd).round(2)
    log("\nby headway (min):\n")
    table(hw)
    flush_notes()


def marey_panel(ax, t: pd.DataFrame, pos: dict[str, dict[str, int]], line: str, dirn: str, date,
                t0, t1, delay_trips: set, broken: str, title: str) -> None:
    p = pos[line]
    m = (t["line"].to_numpy() == line) & (t["dir"].to_numpy() == dirn) & (t["date"].to_numpy() == np.datetime64(date))
    ii = np.where(m)[0]
    for i in ii:
        dep, arr = t["dep_ts"].iat[i], t["arr_ts"].iat[i]
        if arr < t0 or dep > t1:
            continue
        y0, y1 = p.get(str(t["from_station"].iat[i])), p.get(str(t["to_station"].iat[i]))
        tr = str(t["train_id"].iat[i])
        trip = int(t["trip_key"].iat[i])
        if tr == broken:
            ax.plot([dep, arr], [y0, y1], color="black", lw=1.6, zorder=4)
        elif trip in delay_trips:
            ax.plot([dep, arr], [y0, y1], color="#d62728", lw=1.1, zorder=3)
        else:
            ax.plot([dep, arr], [y0, y1], color="0.75", lw=0.6, zorder=1)
    ax.set_title(title, fontsize=9)
    ax.set_xlim(t0, t1)
    ax.grid(alpha=0.25, lw=0.4)
    ax.tick_params(labelsize=7)


