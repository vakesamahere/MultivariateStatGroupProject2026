def build_delay(t: pd.DataFrame) -> pd.DataFrame:
    section("1a. Schedule reconstruction and delay per traversal")
    log("Scheduled times: trip origin departure on the :00/:30 grid, then cumulative segment baseline "
        f"travel (median per route x directed segment) plus {DWELL_S} s dwell per intermediate stop. "
        "Delay increments: x_dwell = dwell - 30 s (origin: seconds past the 30-s grid), "
        "x_travel = travel - baseline.")
    check("traversals with missing baseline", int(t["base_travel_s"].isna().sum()))
    orig = (t["dep_event"] == "DEPARTED_ORIGIN").to_numpy()
    sec = t["dep_ts"].dt.second.to_numpy() + 60 * t["dep_ts"].dt.minute.to_numpy()
    origin_late = np.where(orig, sec % ORIGIN_GRID_S, 0)
    t["x_dwell"] = np.where(orig, origin_late, t["dwell_s"].to_numpy() - DWELL_S).astype(float)
    t["x_travel"] = (t["travel_s"] - t["base_travel_s"]).astype(float)
    g = t.groupby("trip_key", sort=False)
    t["delay_arr"] = g["x_dwell"].cumsum() + g["x_travel"].cumsum()
    t["delay_dep"] = t["delay_arr"] - t["x_travel"]
    t["sched_dep"] = t["dep_ts"] - pd.to_timedelta(t["delay_dep"], unit="s")
    t["sched_arr"] = t["arr_ts"] - pd.to_timedelta(t["delay_arr"], unit="s")
    check("negative dwell increments (dwell < 30 s)", int((t["x_dwell"] < 0).sum()))
    check("negative travel increments (faster than baseline)", int((t["x_travel"] < 0).sum()))
    check("scheduled dep/arr times off the 30-s grid", int(((t["sched_dep"].dt.second % 30) != 0).sum()
                                                         + ((t["sched_arr"].dt.second % 30) != 0).sum()))
    log(f"- origin departures off the :00/:30 grid: {int((origin_late > 0).sum())} of {int(orig.sum())} "
        f"(lateness {sorted(origin_late[origin_late > 0].tolist())} s)")
    log(f"- traversals with arrival delay > 0: {int((t['delay_arr'] > 0).sum()):,} of {len(t):,}; "
        f"max delay {t['delay_arr'].max():.0f} s; delay {q(t.loc[t['delay_arr'] > 0, 'delay_arr'])}")
    # terminal layovers
    last = t["trip_key"].ne(t["trip_key"].shift(-1)).to_numpy()
    nxt_trip_same_train = np.r_[last[:-1] & (t["train_id"].to_numpy()[1:] == t["train_id"].to_numpy()[:-1])
                                & (t["date"].to_numpy()[1:] == t["date"].to_numpy()[:-1]), False]
    term = t.loc[nxt_trip_same_train, ["trip_key", "delay_arr", "arr_ts"]].copy()
    nx = t.loc[np.r_[False, nxt_trip_same_train[:-1]]]
    term["next_origin_late_s"] = nx["x_dwell"].to_numpy()
    term["next_turnaround_s"] = nx["turnaround_s"].to_numpy()
    term["sched_layover_s"] = term["next_turnaround_s"] + term["delay_arr"] - term["next_origin_late_s"]
    dl = term[term["delay_arr"] > 0]
    log(f"- trip-end arrivals followed by another trip of the same train: {len(term):,}; late at terminal: "
        f"{len(dl):,}; of those, next origin departure late: {int((dl['next_origin_late_s'] > 0).sum())}")
    log(f"- scheduled terminal layover: {q(term['sched_layover_s'])} s; after a late arrival, remaining layover "
        f"{q(dl['next_turnaround_s'])} s; max terminal delay / scheduled layover = "
        f"{(dl['delay_arr'] / dl['sched_layover_s']).max():.2f}")
    flush_notes()
    return t


